using System.Net;
using System.Net.Http.Json;
using System.Text.Json;

using FluentAssertions;

using Microsoft.AspNetCore.Mvc.Testing;

namespace HttpEndpointGenerator.Tests.Aot;

/// <summary>
/// Integration tests for the KetPsi specialized RequestDelegate path.
/// Requires EnableRequestDelegateGenerator=true (and CompilerVisibleProperty) so the
/// generator emits MapMethods + ParameterBinder instead of classic Delegate lambdas.
/// After build, check obj/.../KetPsiRdgActivation.g.cs — UseKetPsiRequestDelegate must be true.
/// </summary>
public class RequestDelegatePathIntegrationTests : IClassFixture<WebApplicationFactory<Program>>
{
    private readonly HttpClient _client;

    public RequestDelegatePathIntegrationTests(WebApplicationFactory<Program> factory)
    {
        _client = factory.CreateClient();
    }

    [Fact]
    public async Task Route_Int_Binding_Works()
    {
        var response = await _client.GetAsync("/users/42");
        response.StatusCode.Should().Be(HttpStatusCode.OK);
        var body = await response.Content.ReadFromJsonAsync<JsonElement>();
        body.GetProperty("id").GetInt32().Should().Be(42);
    }

    [Fact]
    public async Task Query_Binding_Works()
    {
        var response = await _client.GetAsync("/orders?status=shipped&page=3&size=5");
        response.StatusCode.Should().Be(HttpStatusCode.OK);
        var body = await response.Content.ReadFromJsonAsync<JsonElement>();
        body.GetProperty("status").GetString().Should().Be("shipped");
        body.GetProperty("page").GetInt32().Should().Be(3);
        body.GetProperty("size").GetInt32().Should().Be(5);
    }

    [Fact]
    public async Task Header_Binding_With_Custom_Name_Works()
    {
        var request = new HttpRequestMessage(HttpMethod.Get, "/orders?status=open");
        request.Headers.Add("X-Tenant-ID", "tenant-a");
        var response = await _client.SendAsync(request);
        response.StatusCode.Should().Be(HttpStatusCode.OK);
        var body = await response.Content.ReadFromJsonAsync<JsonElement>();
        body.GetProperty("tenantId").GetString().Should().Be("tenant-a");
    }

    [Fact]
    public async Task Body_Binding_Post_Works()
    {
        var payload = new { email = "a@b.c", firstName = "A", lastName = "B", roles = new[] { "USER" } };
        var response = await _client.PostAsJsonAsync("/users", payload);
        response.StatusCode.Should().Be(HttpStatusCode.Created);
    }

    [Fact]
    public async Task Invalid_Route_Int_Returns_400()
    {
        var response = await _client.GetAsync("/users/not-a-number");
        response.StatusCode.Should().BeOneOf(HttpStatusCode.BadRequest, HttpStatusCode.NotFound);

        if (response.StatusCode == HttpStatusCode.BadRequest)
        {
            var text = await response.Content.ReadAsStringAsync();
            // Sync RD path: SetBadRequest sets status only (empty body).
            // Async path / WriteBadRequestAsync: "Bad Request".
            // Classic RDF: BadHttpRequestException message (RD path not active).
            text.Should().Match(s =>
                string.IsNullOrEmpty(s) ||
                s == "Bad Request" ||
                s.Contains("Failed to bind parameter", StringComparison.Ordinal));
        }
    }

    [Fact]
    public void Rdg_Activation_Marker_Is_True()
    {
        // Generated by the source generator when EnableRequestDelegateGenerator/PublishAot is visible.
        // If this fails, the CompilerVisibleProperty did not reach the generator — clean rebuild.
        KetPsi.Endpoints.Http.Generated.KetPsiRdgActivation.UseKetPsiRequestDelegate
            .Should().BeTrue(
                "EnableRequestDelegateGenerator=true must be CompilerVisible so the generator emits MapMethods. " +
                "Check obj/.../KetPsiRdgActivation.g.cs and ensure a clean rebuild.");
    }
}
