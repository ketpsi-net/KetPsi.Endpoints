using System.Globalization;

namespace KetPsi.Endpoints.Grpc.Generator;

/// <summary>
/// Emits protobuf codecs: Size_X (exact encoded size), Write_X (direct to IBufferWriter, no intermediate
/// buffers), Read_X (wire-type checked, bounded sub-readers, depth limited) and a contextual Marshaller_X.
/// </summary>
internal static class CodecEmitter
{
    private const string Wire = "global::KetPsi.Endpoints.Grpc.Wire.";
    private const string WT = Wire + "ProtoWireType.";
    private const string SZ = Wire + "ProtoWireSize.";
    private const string Writer = Wire + "ProtoWireWriter";
    private const string Reader = Wire + "ProtoWireReader";

    public static string Emit(OutputPlan plan)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("#nullable disable");
        w.Line("#pragma warning disable CS0612, CS0618 // obsolete members are still serialized");
        w.Line();
        w.Open("namespace KetPsi.Endpoints.Grpc");
        w.Line("/// <summary>Generated protobuf codecs (Size_X / Write_X / Read_X / Marshaller_X).</summary>");
        w.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"KetPsi.Endpoints.Grpc.Generator\", \"2.0\")]");
        w.Open("internal static partial class GeneratedProtoCodecs");
        foreach (var m in plan.Messages.Values.OrderBy(m => m.Name, StringComparer.Ordinal))
            EmitMessage(w, m, plan);
        w.Close();
        w.Close();
        return w.ToString();
    }

    private static string Esc(string name) => RouteResolver.EscapeKeyword(name);

    private static int TagSize(int number, int wireType) => VarintSize((uint)((number << 3) | wireType));

    private static int VarintSize(uint v)
    {
        var n = 1;
        while (v >= 0x80)
        {
            v >>= 7;
            n++;
        }
        return n;
    }

    private static string Inv(int v) => v.ToString(CultureInfo.InvariantCulture);

    private static void EmitMessage(CodeWriter w, ResolvedMessage m, OutputPlan plan)
    {
        var t = m.ClrType;
        var n = m.Name;

        // ---- Size
        w.Line($"/// <summary>Encoded size of a <c>{OutputPlanner.Display(t)}</c> message body.</summary>");
        w.Open($"internal static int Size_{n}({t} value, int depth)");
        w.Line($"{Wire}ProtoWireLimits.CheckDepth(depth);");
        if (m.IsReferenceType)
            w.Line("if (value is null) return 0;");
        w.Line("int size = 0;");
        foreach (var f in m.Fields)
            EmitField(w, f, plan, sizeMode: true);
        w.Line("return size;");
        w.Close();
        w.Line();

        // ---- Write
        w.Line($"/// <summary>Writes a <c>{OutputPlanner.Display(t)}</c> message body.</summary>");
        w.Open($"internal static void Write_{n}(ref {Writer} writer, {t} value)");
        if (m.IsReferenceType)
            w.Line("if (value is null) return;");
        w.Line("writer.EnterMessage();");
        foreach (var f in m.Fields)
            EmitField(w, f, plan, sizeMode: false);
        w.Line("writer.ExitMessage();");
        w.Close();
        w.Line();

        // ---- Read
        w.Line($"/// <summary>Reads a <c>{OutputPlanner.Display(t)}</c> message body.</summary>");
        w.Open($"internal static {t} Read_{n}(ref {Reader} reader)");
        if (m.Plan.Kind == ConstructionKind.Unconstructible)
        {
            w.Line($"throw new global::System.NotSupportedException(\"{OutputPlanner.Display(t)} cannot be constructed for deserialization.\");");
            w.Close();
            w.Line();
        }
        else
        {
            foreach (var f in m.Fields)
                EmitLocal(w, f);
            w.Open("while (reader.TryReadTag(out var __field, out var __wt))");
            w.Open("switch (__field)");
            foreach (var f in m.Fields)
                EmitReadCase(w, f, plan);
            w.Line("default: reader.SkipField(__wt); break;");
            w.Close();
            w.Close();
            EmitConstruction(w, m);
            w.Close();
            w.Line();
        }

        if (m.NeedsEmptyReader)
        {
            w.Open($"private static {t} ReadEmpty_{n}()");
            w.Line($"var __r = new {Reader}(global::System.ReadOnlySpan<byte>.Empty);");
            w.Line($"return Read_{n}(ref __r);");
            w.Close();
            w.Line();
        }

        w.Line("/// <summary>Not a hot path: serializes to a new array (tests / tooling).</summary>");
        w.Line($"public static byte[] Serialize_{n}({t} value) => {Wire}ProtoMarshaller.Serialize<{t}>(value, Write_{n}, Size_{n});");
        w.Line();
        w.Line("/// <summary>Deserializes from a span (throws ProtoWireException on malformed input).</summary>");
        w.Open($"public static {t} Deserialize_{n}(global::System.ReadOnlySpan<byte> payload)");
        w.Line($"var reader = new {Reader}(payload);");
        w.Line($"return Read_{n}(ref reader);");
        w.Close();
        w.Line();
        w.Line($"public static readonly global::Grpc.Core.Marshaller<{t}> Marshaller_{n} = {Wire}ProtoMarshaller.Create<{t}>(Write_{n}, Size_{n}, Read_{n});");
        w.Line();
    }

    // ------------------------------------------------------------------ write / size

    private static int WireTypeOf(ValueKind k) => k switch
    {
        ValueKind.Bool or ValueKind.Int32 or ValueKind.Int64 or ValueKind.UInt32 or ValueKind.UInt64
            or ValueKind.Char or ValueKind.Enum => 0,
        ValueKind.Double => 1,
        ValueKind.Float => 5,
        _ => 2,
    };

    private static string WireTypeName(int wt) => wt switch
    {
        0 => WT + "Varint",
        1 => WT + "Fixed64",
        5 => WT + "Fixed32",
        _ => WT + "LengthDelimited",
    };

    public static bool IsPackable(ValueKind k) => WireTypeOf(k) != 2;

    private static string SizeOf(ValueInfo v, string e, string depthExpr, OutputPlan plan) => v.Kind switch
    {
        ValueKind.Bool => "1",
        ValueKind.Int32 => $"{SZ}Int32((int){e})",
        ValueKind.Enum => $"{SZ}Int32((int){e})",
        ValueKind.UInt32 => $"{SZ}UInt32((uint){e})",
        ValueKind.Int64 => $"{SZ}Int64((long){e})",
        ValueKind.UInt64 => $"{SZ}UInt64((ulong){e})",
        ValueKind.Float => "4",
        ValueKind.Double => "8",
        ValueKind.Char => $"{SZ}Char({e})",
        ValueKind.String => $"{SZ}String({e})",
        ValueKind.Bytes => $"{SZ}Bytes({e})",
        ValueKind.Guid => "37",
        ValueKind.Decimal => $"{SZ}Decimal({e})",
        ValueKind.DateTime or ValueKind.DateTimeOffset or ValueKind.DateOnly => $"{SZ}Timestamp({e})",
        ValueKind.TimeSpan or ValueKind.TimeOnly => $"{SZ}Duration({e})",
        ValueKind.Message => $"{SZ}LengthPrefixed(Size_{plan.MessageName(v.RefKey)}({e}, {depthExpr}))",
        _ => "0",
    };

    private static void WriteValue(CodeWriter w, ValueInfo v, string e, OutputPlan plan)
    {
        switch (v.Kind)
        {
            case ValueKind.Bool: w.Line($"writer.WriteBool({e});"); break;
            case ValueKind.Int32:
            case ValueKind.Enum: w.Line($"writer.WriteInt32((int){e});"); break;
            case ValueKind.UInt32: w.Line($"writer.WriteUInt32((uint){e});"); break;
            case ValueKind.Int64: w.Line($"writer.WriteInt64((long){e});"); break;
            case ValueKind.UInt64: w.Line($"writer.WriteUInt64((ulong){e});"); break;
            case ValueKind.Float: w.Line($"writer.WriteFloat({e});"); break;
            case ValueKind.Double: w.Line($"writer.WriteDouble({e});"); break;
            case ValueKind.Char: w.Line($"writer.WriteChar({e});"); break;
            case ValueKind.String: w.Line($"writer.WriteString({e});"); break;
            case ValueKind.Bytes: w.Line($"writer.WriteBytes({e});"); break;
            case ValueKind.Guid: w.Line($"writer.WriteGuid({e});"); break;
            case ValueKind.Decimal: w.Line($"writer.WriteDecimal({e});"); break;
            case ValueKind.DateTime:
            case ValueKind.DateTimeOffset:
            case ValueKind.DateOnly: w.Line($"writer.WriteTimestamp({e});"); break;
            case ValueKind.TimeSpan:
            case ValueKind.TimeOnly: w.Line($"writer.WriteDuration({e});"); break;
            case ValueKind.Message:
            {
                var name = plan.MessageName(v.RefKey);
                w.Line($"writer.WriteLength(Size_{name}({e}, writer.Depth + 1));");
                w.Line($"Write_{name}(ref writer, {e});");
                break;
            }
        }
    }

    /// <summary>Condition for writing a non-nullable singular value (proto3 implicit presence: skip defaults).</summary>
    private static string ImplicitPresence(ValueInfo v, string e) => v.Kind switch
    {
        ValueKind.Bool => e,
        ValueKind.Int32 or ValueKind.Int64 or ValueKind.UInt32 or ValueKind.UInt64 or ValueKind.Char or ValueKind.Enum => $"{e} != 0",
        ValueKind.Float => $"global::System.BitConverter.SingleToInt32Bits({e}) != 0",
        ValueKind.Double => $"global::System.BitConverter.DoubleToInt64Bits({e}) != 0",
        ValueKind.String => $"!string.IsNullOrEmpty({e})",
        ValueKind.Bytes => $"{e} is not null && {e}.Length != 0",
        ValueKind.Guid => $"{e} != global::System.Guid.Empty",
        ValueKind.Decimal => $"{e} != 0m",
        ValueKind.DateTime or ValueKind.DateTimeOffset or ValueKind.DateOnly or ValueKind.TimeSpan or ValueKind.TimeOnly => $"{e} != default",
        ValueKind.Message => v.IsValueType ? "true" : $"{e} is not null",
        _ => "false",
    };

    private static bool IsRefValue(ValueInfo v)
        => v.Kind is ValueKind.String or ValueKind.Bytes || (v.Kind == ValueKind.Message && !v.IsValueType);

    private static void EmitField(CodeWriter w, ResolvedField f, OutputPlan plan, bool sizeMode)
    {
        var fm = f.Model;
        var access = "value." + Esc(fm.Name);
        var num = f.Number;
        var v = fm.Value;
        var depthExpr = sizeMode ? "depth + 1" : "writer.Depth + 1";
        var local = "__v" + Inv(num);

        switch (fm.Shape)
        {
            case FieldShape.Single:
            {
                var wt = WireTypeOf(v.Kind);
                var tagSize = TagSize(num, wt);
                w.Open();
                string cond, expr;
                if (fm.IsNullable && v.IsValueType)
                {
                    w.Line($"var {local} = {access};");
                    cond = $"{local}.HasValue";
                    expr = $"{local}.GetValueOrDefault()";
                }
                else if (fm.IsNullable)
                {
                    w.Line($"var {local} = {access};");
                    cond = $"{local} is not null";
                    expr = local;
                }
                else
                {
                    w.Line($"var {local} = {access};");
                    cond = ImplicitPresence(v, local);
                    expr = local;
                }
                w.Open($"if ({cond})");
                if (sizeMode)
                    w.Line($"size += {Inv(tagSize)} + {SizeOf(v, expr, depthExpr, plan)};");
                else
                {
                    w.Line($"writer.WriteTag({Inv(num)}, {WireTypeName(wt)});");
                    WriteValue(w, v, expr, plan);
                }
                w.Close();
                w.Close();
                break;
            }
            case FieldShape.Repeated:
            {
                var wt = WireTypeOf(v.Kind);
                var notNull = fm.Collection == CollectionKind.ImmutableArray ? $"!{local}.IsDefault" : $"{local} is not null";
                w.Open();
                w.Line($"var {local} = {access};");
                w.Open($"if ({notNull})");
                if (IsPackable(v.Kind))
                {
                    var tagSize = TagSize(num, 2);
                    w.Line("int __len = 0, __n = 0;");
                    Iterate(w, fm.Collection, local, "__e", () =>
                    {
                        w.Line($"__len += {SizeOf(v, "__e", depthExpr, plan)};");
                        w.Line("__n++;");
                    });
                    if (sizeMode)
                        w.Line($"if (__n != 0) size += {Inv(tagSize)} + {SZ}LengthPrefixed(__len);");
                    else
                    {
                        w.Open("if (__n != 0)");
                        w.Line($"writer.WriteTag({Inv(num)}, {WT}LengthDelimited);");
                        w.Line("writer.WriteLength(__len);");
                        Iterate(w, fm.Collection, local, "__e", () => WriteValue(w, v, "__e", plan));
                        w.Close();
                    }
                }
                else
                {
                    var tagSize = TagSize(num, wt);
                    Iterate(w, fm.Collection, local, "__e", () =>
                    {
                        if (sizeMode)
                            w.Line($"size += {Inv(tagSize)} + {SizeOf(v, "__e", depthExpr, plan)};");
                        else
                        {
                            w.Line($"writer.WriteTag({Inv(num)}, {WireTypeName(wt)});");
                            WriteValue(w, v, "__e", plan);
                        }
                    });
                }
                w.Close();
                w.Close();
                break;
            }
            case FieldShape.Map:
            {
                var k = fm.MapKey!;
                var kwt = WireTypeOf(k.Kind);
                var vwt = WireTypeOf(v.Kind);
                var entryTag = TagSize(num, 2);
                w.Open();
                w.Line($"var {local} = {access};");
                w.Open($"if ({local} is not null)");
                w.Open($"foreach (var __kv in {local})");
                w.Line("var __k = __kv.Key;");
                w.Line("var __mv = __kv.Value;");
                var present = IsRefValue(v) ? "__mv is not null" : "true";
                w.Line($"int __es = {Inv(TagSize(1, kwt))} + {SizeOf(k, "__k", depthExpr, plan)} + ({present} ? {Inv(TagSize(2, vwt))} + {SizeOf(v, "__mv", depthExpr, plan)} : 0);");
                if (sizeMode)
                    w.Line($"size += {Inv(entryTag)} + {SZ}LengthPrefixed(__es);");
                else
                {
                    w.Line($"writer.WriteTag({Inv(num)}, {WT}LengthDelimited);");
                    w.Line("writer.WriteLength(__es);");
                    w.Line($"writer.WriteTag(1, {WireTypeName(kwt)});");
                    WriteValue(w, k, "__k", plan);
                    w.Open($"if ({present})");
                    w.Line($"writer.WriteTag(2, {WireTypeName(vwt)});");
                    WriteValue(w, v, "__mv", plan);
                    w.Close();
                }
                w.Close();
                w.Close();
                w.Close();
                break;
            }
        }
    }

    private static void Iterate(CodeWriter w, CollectionKind kind, string collection, string element, Action body)
    {
        if (kind == CollectionKind.IndexedInterface)
        {
            w.Open($"for (int __i = 0; __i < {collection}.Count; __i++)");
            w.Line($"var {element} = {collection}[__i];");
        }
        else
        {
            w.Open($"foreach (var {element} in {collection})");
        }
        body();
        w.Close();
    }

    // ------------------------------------------------------------------ read

    private static string ElemClr(ValueInfo v) => v.ClrType;

    private static string ListType(string elem) => $"global::System.Collections.Generic.List<{elem}>";
    private static string SetType(string elem) => $"global::System.Collections.Generic.HashSet<{elem}>";
    private static string DictType(ValueInfo k, ValueInfo v) => $"global::System.Collections.Generic.Dictionary<{k.ClrType}, {v.ClrType}>";
    private static string ArrayBuilder(string elem) => $"{Wire}ProtoArrayBuilder<{elem}>";

    private static bool UsesArrayBuilder(CollectionKind k) => k is CollectionKind.Array or CollectionKind.ImmutableArray;
    private static bool UsesSet(CollectionKind k) => k is CollectionKind.HashSet or CollectionKind.SetInterface;

    private static string LocalOf(ResolvedField f) => "__f" + Inv(f.Number);

    private static void EmitLocal(CodeWriter w, ResolvedField f)
    {
        var fm = f.Model;
        var v = fm.Value;
        var local = LocalOf(f);
        switch (fm.Shape)
        {
            case FieldShape.Map:
                w.Line($"{DictType(fm.MapKey!, v)} {local} = null;");
                break;
            case FieldShape.Repeated:
                if (UsesArrayBuilder(fm.Collection))
                    w.Line($"{ArrayBuilder(ElemClr(v))} {local} = default;");
                else if (UsesSet(fm.Collection))
                    w.Line($"{SetType(ElemClr(v))} {local} = null;");
                else
                    w.Line($"{ListType(ElemClr(v))} {local} = null;");
                break;
            default:
            {
                var type = fm.IsNullable && v.IsValueType ? v.ClrType + "?" : v.ClrType;
                var init = !fm.IsNullable && v.Kind == ValueKind.String ? "\"\""
                    : !fm.IsNullable && v.Kind == ValueKind.Bytes ? "global::System.Array.Empty<byte>()"
                    : "default";
                w.Line($"{type} {local} = {init};");
                break;
            }
        }
    }

    /// <summary>Emits statements reading one value from <paramref name="r"/> and passing it to <paramref name="sink"/>.</summary>
    private static void ReadValue(CodeWriter w, ValueInfo v, string r, OutputPlan plan, Func<string, string> sink, string uniq)
    {
        string expr;
        switch (v.Kind)
        {
            case ValueKind.Bool: expr = $"{r}.ReadBool()"; break;
            case ValueKind.Int32:
                expr = v.ClrType == "int" ? $"{r}.ReadInt32()" : $"unchecked(({v.ClrType}){r}.ReadInt32())";
                break;
            case ValueKind.UInt32:
                expr = v.ClrType == "uint" ? $"{r}.ReadUInt32()" : $"unchecked(({v.ClrType}){r}.ReadUInt32())";
                break;
            case ValueKind.Int64:
                expr = v.ClrType == "long" ? $"{r}.ReadInt64()" : $"unchecked(({v.ClrType}){r}.ReadInt64())";
                break;
            case ValueKind.UInt64:
                expr = v.ClrType == "ulong" ? $"{r}.ReadUInt64()" : $"unchecked(({v.ClrType}){r}.ReadUInt64())";
                break;
            case ValueKind.Enum: expr = $"({v.ClrType}){r}.ReadInt32()"; break;
            case ValueKind.Float: expr = $"{r}.ReadFloat()"; break;
            case ValueKind.Double: expr = $"{r}.ReadDouble()"; break;
            case ValueKind.Char: expr = $"{r}.ReadChar()"; break;
            case ValueKind.String: expr = $"{r}.ReadString()"; break;
            case ValueKind.Bytes: expr = $"{r}.ReadBytes().ToArray()"; break;
            case ValueKind.Guid: expr = $"{r}.ReadGuid()"; break;
            case ValueKind.Decimal: expr = $"{r}.ReadDecimal()"; break;
            case ValueKind.DateTime: expr = $"{r}.ReadTimestamp()"; break;
            case ValueKind.DateTimeOffset: expr = $"{r}.ReadTimestampOffset()"; break;
            case ValueKind.DateOnly: expr = $"{r}.ReadDateOnly()"; break;
            case ValueKind.TimeSpan: expr = $"{r}.ReadDuration()"; break;
            case ValueKind.TimeOnly: expr = $"{r}.ReadTimeOnly()"; break;
            case ValueKind.Message:
            {
                var sub = "__sub" + uniq;
                w.Line($"var {sub} = {r}.ReadMessage();");
                expr = $"Read_{plan.MessageName(v.RefKey)}(ref {sub})";
                break;
            }
            default:
                w.Line($"{r}.SkipField(__wt);");
                return;
        }
        w.Line(sink(expr));
    }

    private static void EmitReadCase(CodeWriter w, ResolvedField f, OutputPlan plan)
    {
        var fm = f.Model;
        var v = fm.Value;
        var local = LocalOf(f);
        var uniq = Inv(f.Number);
        w.Open($"case {Inv(f.Number)}:");
        switch (fm.Shape)
        {
            case FieldShape.Single:
                w.Open($"if (__wt == {WireTypeName(WireTypeOf(v.Kind))})");
                ReadValue(w, v, "reader", plan, e => $"{local} = {e};", uniq);
                w.Close();
                w.Line("else reader.SkipField(__wt);");
                break;

            case FieldShape.Repeated:
            {
                var elem = ElemClr(v);
                string Add(string e) => UsesArrayBuilder(fm.Collection)
                    ? $"{local}.Add({e});"
                    : UsesSet(fm.Collection)
                        ? $"({local} ??= new {SetType(elem)}()).Add({e});"
                        : $"({local} ??= new {ListType(elem)}()).Add({e});";

                if (IsPackable(v.Kind))
                {
                    var wt = WireTypeOf(v.Kind);
                    w.Open($"if (__wt == {WT}LengthDelimited)");
                    w.Line("var __packed = reader.ReadPacked();");
                    var count = wt switch
                    {
                        5 => "__packed.Remaining / 4",
                        1 => "__packed.Remaining / 8",
                        _ => "__packed.CountRemainingVarints()",
                    };
                    if (UsesArrayBuilder(fm.Collection))
                        w.Line($"{local}.EnsureCapacity({count});");
                    else if (UsesSet(fm.Collection))
                        w.Line($"({local} ??= new {SetType(elem)}()).EnsureCapacity({local}.Count + {count});");
                    else
                        w.Line($"({local} ??= new {ListType(elem)}()).EnsureCapacity({local}.Count + {count});");
                    w.Open("while (!__packed.IsAtEnd)");
                    ReadValue(w, v, "__packed", plan, Add, uniq);
                    w.Close();
                    w.Close();
                    w.Open($"else if (__wt == {WireTypeName(wt)})");
                    ReadValue(w, v, "reader", plan, Add, uniq);
                    w.Close();
                    w.Line("else reader.SkipField(__wt);");
                }
                else
                {
                    w.Open($"if (__wt == {WT}LengthDelimited)");
                    ReadValue(w, v, "reader", plan, Add, uniq);
                    w.Close();
                    w.Line("else reader.SkipField(__wt);");
                }
                break;
            }

            case FieldShape.Map:
            {
                var k = fm.MapKey!;
                w.Open($"if (__wt == {WT}LengthDelimited)");
                w.Line("var __entry = reader.ReadMessage();");
                w.Line($"{k.ClrType} __key = {MissingDefault(k, plan)};");
                var valueInit = v.Kind == ValueKind.Message && !v.IsValueType ? "default" : MissingDefault(v, plan);
                w.Line($"{v.ClrType} __val = {valueInit};");
                if (v.Kind == ValueKind.Message && !v.IsValueType)
                    w.Line("bool __hasVal = false;");
                w.Open("while (__entry.TryReadTag(out var __ef, out var __ewt))");
                w.Open($"if (__ef == 1 && __ewt == {WireTypeName(WireTypeOf(k.Kind))})");
                ReadValue(w, k, "__entry", plan, e => $"__key = {e};", uniq + "k");
                w.Close();
                w.Open($"else if (__ef == 2 && __ewt == {WireTypeName(WireTypeOf(v.Kind))})");
                ReadValue(w, v, "__entry", plan, e => v.Kind == ValueKind.Message && !v.IsValueType ? $"__val = {e}; __hasVal = true;" : $"__val = {e};", uniq + "v");
                w.Close();
                w.Line("else __entry.SkipField(__ewt);");
                w.Close();
                if (v.Kind == ValueKind.Message && !v.IsValueType)
                    w.Line($"if (!__hasVal) __val = ReadEmpty_{plan.MessageName(v.RefKey)}();");
                w.Line($"({local} ??= new {DictType(k, v)}())[__key] = __val;");
                w.Close();
                w.Line("else reader.SkipField(__wt);");
                break;
            }
        }
        w.Line("break;");
        w.Close();
    }

    /// <summary>Value used for a missing map key / value (proto3 defaults).</summary>
    private static string MissingDefault(ValueInfo v, OutputPlan plan) => v.Kind switch
    {
        ValueKind.String => "\"\"",
        ValueKind.Bytes => "global::System.Array.Empty<byte>()",
        _ => "default",
    };

    private static string FieldValueExpr(ResolvedField f)
    {
        var fm = f.Model;
        var local = LocalOf(f);
        var elem = fm.Value.ClrType;
        switch (fm.Shape)
        {
            case FieldShape.Map:
                return $"{local} ?? new {DictType(fm.MapKey!, fm.Value)}()";
            case FieldShape.Repeated:
                return fm.Collection switch
                {
                    CollectionKind.Array => $"{local}.ToArray()",
                    CollectionKind.ImmutableArray => $"global::System.Runtime.InteropServices.ImmutableCollectionsMarshal.AsImmutableArray({local}.ToArray())",
                    CollectionKind.ImmutableList => $"{local} is null ? global::System.Collections.Immutable.ImmutableList<{elem}>.Empty : global::System.Collections.Immutable.ImmutableList.CreateRange({local})",
                    CollectionKind.HashSet or CollectionKind.SetInterface => $"{local} ?? new {SetType(elem)}()",
                    _ => $"{local} ?? new {ListType(elem)}()",
                };
            default:
                return local;
        }
    }

    private static void EmitConstruction(CodeWriter w, ResolvedMessage m)
    {
        var plan = m.Plan;
        var byName = m.Fields.ToDictionary(f => f.Name, StringComparer.Ordinal);
        if (plan.Kind == ConstructionKind.Factory)
        {
            var args = string.Join(", ", plan.Arguments.Select(a => "(" + FieldValueExpr(byName[a.Field]) + ")"));
            w.Line($"return {plan.FactoryTarget}({args});");
            return;
        }

        var ctorArgs = string.Join(", ", plan.Arguments.Select(a => Esc(a.Param) + ": " + FieldValueExpr(byName[a.Field])));
        if (plan.Initializers.Count == 0)
        {
            w.Line($"return new {m.ClrType}({ctorArgs});");
            return;
        }
