using System.Globalization;

namespace KetPsi.Endpoints.Grpc.Generator;

/// <summary>
/// Emits one empty service class per proto service (registered as a singleton, so activation does not
/// allocate), static <c>Method</c> descriptors, an <c>IServiceMethodProvider</c>, and per-method invokers.
/// Handlers are resolved from request services per call; interceptor chains use cached static delegates.
/// </summary>
internal static class ServiceEmitter
{
    private const string Empty = "global::KetPsi.Endpoints.Grpc.GrpcEmpty";
    private const string Core = "global::Grpc.Core.";
    private const string Ctx = "global::Grpc.Core.ServerCallContext";

    public static string ServiceIdent(string serviceFullName)
        => serviceFullName.Replace("_", "__").Replace(".", "_");

    public static string Emit(OutputPlan plan)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("#nullable disable");
        w.Line("#pragma warning disable CS0612, CS0618");
        w.Line();
        w.Open("namespace KetPsi.Endpoints.Grpc");
        foreach (var svc in Services(plan))
            EmitService(w, svc.Key, svc.ToList(), plan);
        w.Close();
        return w.ToString();
    }

    public static IEnumerable<IGrouping<string, ResolvedEndpoint>> Services(OutputPlan plan)
        => plan.Endpoints.GroupBy(e => e.Model.ServiceFullName, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal);

    public static string RequestClr(ResolvedEndpoint ep) => ep.Model.RequestType.Length == 0 ? Empty : ep.Model.RequestType;
    public static string ResponseClr(ResolvedEndpoint ep) => ep.Model.ResponseType.Length == 0 ? Empty : ep.Model.ResponseType;

    private static string Marshaller(string clr, OutputPlan plan)
        => clr == Empty ? Empty + ".Marshaller" : "GeneratedProtoCodecs.Marshaller_" + plan.MessageName(clr);

    private static string Esc(string s) => RouteResolver.EscapeKeyword(s);

    private static void EmitService(CodeWriter w, string serviceFullName, List<ResolvedEndpoint> methods, OutputPlan plan)
    {
        var id = ServiceIdent(serviceFullName);
        methods = methods.OrderBy(m => m.Model.Method, StringComparer.Ordinal).ToList();

        w.Line($"/// <summary>gRPC service <c>{serviceFullName}</c> (stateless; methods are bound by <see cref=\"{id}_ServiceMethodProvider\"/>).</summary>");
        w.Line($"internal sealed class {id}_GrpcService {{ }}");
        w.Line();

        w.Open($"internal static class {id}_GrpcMethods");
        foreach (var m in methods)
        {
            var req = RequestClr(m);
            var res = ResponseClr(m);
            var type = m.Model.Kind switch
            {
                RpcKind.Unary => "Unary",
                RpcKind.ClientStreaming => "ClientStreaming",
                RpcKind.ServerStreaming => "ServerStreaming",
                _ => "DuplexStreaming",
            };
            w.Line($"public static readonly {Core}Method<{req}, {res}> {Esc(m.Model.Method)} = new {Core}Method<{req}, {res}>(");
            w.Line($"    {Core}MethodType.{type}, \"{serviceFullName}\", \"{m.Model.Method}\", {Marshaller(req, plan)}, {Marshaller(res, plan)});");
        }
        w.Close();
        w.Line();

        w.Open($"internal sealed class {id}_ServiceMethodProvider : global::Grpc.AspNetCore.Server.Model.IServiceMethodProvider<{id}_GrpcService>");
        w.Open($"public void OnServiceMethodDiscovery(global::Grpc.AspNetCore.Server.Model.ServiceMethodProviderContext<{id}_GrpcService> context)");
        foreach (var m in methods)
        {
            var name = Esc(m.Model.Method);
            var method = $"{id}_GrpcMethods.{name}";
            var inv = $"{id}_GrpcHandlers.{name}";
            switch (m.Model.Kind)
            {
                case RpcKind.Unary:
                    w.Line($"context.AddUnaryMethod({method}, new global::System.Collections.Generic.List<object>(), static (_, request, ctx) => {inv}(request, ctx));");
                    break;
                case RpcKind.ClientStreaming:
                    w.Line($"context.AddClientStreamingMethod({method}, new global::System.Collections.Generic.List<object>(), static (_, requests, ctx) => {inv}(requests, ctx));");
                    break;
                case RpcKind.ServerStreaming:
                    w.Line($"context.AddServerStreamingMethod({method}, new global::System.Collections.Generic.List<object>(), static (_, request, responses, ctx) => {inv}(request, responses, ctx));");
                    break;
                default:
                    w.Line($"context.AddDuplexStreamingMethod({method}, new global::System.Collections.Generic.List<object>(), static (_, requests, responses, ctx) => {inv}(requests, responses, ctx));");
                    break;
            }
        }
        w.Close();
        w.Close();
        w.Line();

        w.Open($"internal static class {id}_GrpcHandlers");
        foreach (var m in methods)
            EmitInvoker(w, m);
        w.Close();
        w.Line();
    }

    private static string Resolve(string type, string ctx)
        => $"global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{type}>(global::Grpc.Core.ServerCallContextExtensions.GetHttpContext({ctx}).RequestServices)";

    private static void EmitInvoker(CodeWriter w, ResolvedEndpoint ep)
    {
        var m = ep.Model;
        var name = Esc(m.Method);
        var req = RequestClr(ep);
        var res = ResponseClr(ep);
        var core = ep.Interceptors.Count == 0 ? name : name + "_Core";
        var ct = "context.CancellationToken";

        string Call(string requestArg)
        {
            var args = new List<string>();
            if (m.HasRequestParameter)
                args.Add(requestArg);
            if (m.PassesCancellationToken)
                args.Add(ct);
            return $"__handler.ExecuteAsync({string.Join(", ", args)})";
        }

        switch (m.Kind)
        {
            case RpcKind.Unary:
            {
                var isAsync = m.ReturnKind is HandlerReturnKind.TaskVoid or HandlerReturnKind.ValueTaskVoid;
                w.Open($"internal static {(isAsync ? "async " : "")}global::System.Threading.Tasks.Task<{res}> {core}({req} request, {Ctx} context)");
                w.Line($"var __handler = {Resolve(m.HandlerType, "context")};");
                EmitBindings(w, ep);
                var call = Call("request");
                switch (m.ReturnKind)
                {
                    case HandlerReturnKind.Task: w.Line($"return {call};"); break;
                    case HandlerReturnKind.ValueTask: w.Line($"return {call}.AsTask();"); break;
                    case HandlerReturnKind.Sync: w.Line($"return global::System.Threading.Tasks.Task.FromResult({call});"); break;
                    case HandlerReturnKind.TaskVoid:
                    case HandlerReturnKind.ValueTaskVoid:
                        w.Line($"await {call}.ConfigureAwait(false);");
                        w.Line($"return {Empty}.Instance;");
                        break;
                    case HandlerReturnKind.Void:
                        w.Line($"{call};");
                        w.Line($"return s_{name}_empty;");
                        break;
                }
                w.Close();
                if (m.ReturnKind == HandlerReturnKind.Void)
                    w.Line($"private static readonly global::System.Threading.Tasks.Task<{Empty}> s_{name}_empty = global::System.Threading.Tasks.Task.FromResult({Empty}.Instance);");
                EmitChain(w, ep, name, $"{Core}UnaryServerMethod<{req}, {res}>", "UnaryServerHandler",
                    $"global::System.Threading.Tasks.Task<{res}>", $"{req} request, {Ctx} context", "request, context", "(r, c)", "r, c");
                break;
            }
            case RpcKind.ClientStreaming:
            {
                w.Open($"internal static global::System.Threading.Tasks.Task<{res}> {core}({Core}IAsyncStreamReader<{req}> requests, {Ctx} context)");
                w.Line($"var __handler = {Resolve(m.HandlerType, "context")};");
                var call = Call($"global::KetPsi.Endpoints.Grpc.GrpcStreamAdapters.ReadAll(requests, {ct})");
                w.Line(m.ReturnKind switch
                {
                    HandlerReturnKind.ValueTask => $"return {call}.AsTask();",
                    HandlerReturnKind.Sync => $"return global::System.Threading.Tasks.Task.FromResult({call});",
                    _ => $"return {call};",
                });
                w.Close();
                EmitChain(w, ep, name, $"{Core}ClientStreamingServerMethod<{req}, {res}>", "ClientStreamingServerHandler",
                    $"global::System.Threading.Tasks.Task<{res}>", $"{Core}IAsyncStreamReader<{req}> requests, {Ctx} context", "requests, context", "(r, c)", "r, c");
                break;
            }
            case RpcKind.ServerStreaming:
            {
                w.Open($"internal static async global::System.Threading.Tasks.Task {core}({req} request, {Core}IServerStreamWriter<{res}> responses, {Ctx} context)");
                w.Line($"var __handler = {Resolve(m.HandlerType, "context")};");
                EmitBindings(w, ep);
                w.Open($"await foreach (var __item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.WithCancellation({Call("request")}, {ct}).ConfigureAwait(false))");
                w.Line("await responses.WriteAsync(__item).ConfigureAwait(false);");
                w.Close();
                w.Close();
                EmitChain(w, ep, name, $"{Core}ServerStreamingServerMethod<{req}, {res}>", "ServerStreamingServerHandler",
                    "global::System.Threading.Tasks.Task", $"{req} request, {Core}IServerStreamWriter<{res}> responses, {Ctx} context",
                    "request, responses, context", "(r, s, c)", "r, s, c");
                break;
            }
            default:
            {
                w.Open($"internal static async global::System.Threading.Tasks.Task {core}({Core}IAsyncStreamReader<{req}> requests, {Core}IServerStreamWriter<{res}> responses, {Ctx} context)");
                w.Line($"var __handler = {Resolve(m.HandlerType, "context")};");
                var call = Call($"global::KetPsi.Endpoints.Grpc.GrpcStreamAdapters.ReadAll(requests, {ct})");
                w.Open($"await foreach (var __item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.WithCancellation({call}, {ct}).ConfigureAwait(false))");
                w.Line("await responses.WriteAsync(__item).ConfigureAwait(false);");
                w.Close();
                w.Close();
                EmitChain(w, ep, name, $"{Core}DuplexStreamingServerMethod<{req}, {res}>", "DuplexStreamingServerHandler",
                    "global::System.Threading.Tasks.Task", $"{Core}IAsyncStreamReader<{req}> requests, {Core}IServerStreamWriter<{res}> responses, {Ctx} context",
                    "requests, responses, context", "(r, s, c)", "r, s, c");
                break;
            }
        }
        w.Line();
    }

    /// <summary>
    /// Interceptor chain built from static lambdas cached in static fields: no closures or delegates are
    /// allocated per call. Each interceptor is resolved from the call's request services.
    /// </summary>
    private static void EmitChain(CodeWriter w, ResolvedEndpoint ep, string name, string delegateType, string handlerMethod,
        string returnType, string entryParams, string entryArgs, string lambdaParams, string lambdaArgs)
    {
        var interceptors = ep.Interceptors;
        if (interceptors.Count == 0)
            return;
        var ctxVar = lambdaArgs.Split(',').Last().Trim();
        for (var i = 1; i < interceptors.Count; i++)
        {
            var next = i + 1 < interceptors.Count ? $"s_{name}_{(i + 1).ToString(CultureInfo.InvariantCulture)}" : $"s_{name}_core";
            w.Line($"private static readonly {delegateType} s_{name}_{i.ToString(CultureInfo.InvariantCulture)} = static {lambdaParams} => {Resolve(interceptors[i], ctxVar)}.{handlerMethod}({lambdaArgs}, {next});");
        }
        w.Line($"private static readonly {delegateType} s_{name}_core = static {lambdaParams} => {name}_Core({lambdaArgs});");
        var first = interceptors.Count > 1 ? $"s_{name}_1" : $"s_{name}_core";
        w.Line($"internal static {returnType} {name}({entryParams})");
        w.Line($"    => {Resolve(interceptors[0], "context")}.{handlerMethod}({entryArgs}, {first});");
    }

    private static void EmitBindings(CodeWriter w, ResolvedEndpoint ep)
    {
        var i = 0;
        foreach (var b in ep.Bindings)
        {
            var mv = "__mv" + i.ToString(CultureInfo.InvariantCulture);
            var pv = "__pv" + i.ToString(CultureInfo.InvariantCulture);
            var target = "request." + Esc(b.Property);
            var key = Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(b.HeaderKey, quote: true);
            w.Open($"if (global::KetPsi.Endpoints.Grpc.GrpcMetadataBinder.TryGetString(context.RequestHeaders, {key}, out var {mv}))");
            const string inv = "global::System.Globalization.CultureInfo.InvariantCulture";
            const string ns = "global::System.Globalization.NumberStyles.";
            const string ds = "global::System.Globalization.DateTimeStyles.";
            string? parse = b.Parse switch
            {
                BindingParseKind.String => null,
                BindingParseKind.Int32 or BindingParseKind.Int64 or BindingParseKind.Int16 or BindingParseKind.Byte
                    or BindingParseKind.SByte or BindingParseKind.UInt16 or BindingParseKind.UInt32 or BindingParseKind.UInt64
                    => $"{b.ClrType}.TryParse({mv}, {ns}Integer, {inv}, out var {pv})",
                BindingParseKind.Single or BindingParseKind.Double => $"{b.ClrType}.TryParse({mv}, {ns}Float | {ns}AllowThousands, {inv}, out var {pv})",
                BindingParseKind.Decimal => $"decimal.TryParse({mv}, {ns}Number, {inv}, out var {pv})",
                BindingParseKind.Bool => $"bool.TryParse({mv}, out var {pv})",
                BindingParseKind.Guid => $"global::System.Guid.TryParse({mv}, out var {pv})",
                BindingParseKind.DateTime => $"global::System.DateTime.TryParse({mv}, {inv}, {ds}RoundtripKind, out var {pv})",
                BindingParseKind.DateTimeOffset => $"global::System.DateTimeOffset.TryParse({mv}, {inv}, {ds}RoundtripKind, out var {pv})",
                BindingParseKind.TimeSpan => $"global::System.TimeSpan.TryParse({mv}, {inv}, out var {pv})",
                BindingParseKind.DateOnly => $"global::System.DateOnly.TryParse({mv}, {inv}, {ds}None, out var {pv})",
                BindingParseKind.TimeOnly => $"global::System.TimeOnly.TryParse({mv}, {inv}, {ds}None, out var {pv})",
                BindingParseKind.Char => null,
                BindingParseKind.Enum => $"global::System.Enum.TryParse<{b.ClrType}>({mv}, true, out var {pv})",
                _ => null,
            };
            if (b.Parse == BindingParseKind.String)
                w.Line($"{target} = {mv};");
            else if (b.Parse == BindingParseKind.Char)
                w.Line($"if ({mv}.Length == 1) {target} = {mv}[0];");
            else
                w.Line($"if ({parse}) {target} = {pv};");
            w.Close();
            i++;
        }
    }
}
