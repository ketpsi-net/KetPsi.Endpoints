using System.Text;

namespace KetPsi.Endpoints.Grpc.Generator;

/// <summary>
/// Emits one proto3 file per proto package. Each file is self-contained: it defines every message and
/// enum its services use (shared DTOs are repeated per package, which is wire-compatible), so the
/// <c>package</c> line always matches the server route <c>/package.Service/Method</c>.
/// </summary>
internal static class SchemaEmitter
{
    internal sealed record ProtoFile(string FileName, string Package, string Content);

    public static List<ProtoFile> Emit(OutputPlan plan)
    {
        var files = new List<ProtoFile>();
        foreach (var pkg in plan.Endpoints.GroupBy(e => e.Model.Package, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal))
            files.Add(new ProtoFile(pkg.Key + ".proto", pkg.Key, EmitPackage(pkg.Key, pkg.ToList(), plan)));
        return files;
    }

    private static string EmitPackage(string package, List<ResolvedEndpoint> endpoints, OutputPlan plan)
    {
        // Collect messages / enums reachable from this package's RPCs
        var messages = new List<ResolvedMessage>();
        var enums = new SortedDictionary<string, ResolvedEnum>(StringComparer.Ordinal);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var stack = new Stack<string>();
        foreach (var ep in endpoints)
        {
            if (ep.Model.ResponseType.Length > 0) stack.Push(ep.Model.ResponseType);
            if (ep.Model.RequestType.Length > 0) stack.Push(ep.Model.RequestType);
        }
        while (stack.Count > 0)
        {
            var key = stack.Pop();
            if (!seen.Add(key) || !plan.Messages.TryGetValue(key, out var m))
                continue;
            messages.Add(m);
            foreach (var f in m.Fields)
            {
                foreach (var v in new[] { f.Model.Value, f.Model.MapKey })
                {
                    if (v is null) continue;
                    if (v.Kind == ValueKind.Message) stack.Push(v.RefKey);
                    if (v.Kind == ValueKind.Enum && plan.Enums.TryGetValue(v.RefKey, out var e)) enums[e.Name] = e;
                }
            }
        }
        messages.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));

        var imports = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var m in messages)
        {
            foreach (var f in m.Fields)
            {
                switch (f.Model.Value.Kind)
                {
                    case ValueKind.DateTime or ValueKind.DateTimeOffset or ValueKind.DateOnly:
                        imports.Add("google/protobuf/timestamp.proto");
                        break;
                    case ValueKind.TimeSpan or ValueKind.TimeOnly:
                        imports.Add("google/protobuf/duration.proto");
                        break;
                }
            }
        }
        if (endpoints.Any(e => e.Model.RequestType.Length == 0 || e.Model.ResponseType.Length == 0))
            imports.Add("google/protobuf/empty.proto");

        var sb = new StringBuilder();
        sb.Append("// Generated by KetPsi.Endpoints.Grpc. Do not edit.\n");
        sb.Append("syntax = \"proto3\";\n\n");
        sb.Append("package ").Append(package).Append(";\n");
        if (imports.Count > 0)
        {
            sb.Append('\n');
            foreach (var i in imports)
                sb.Append("import \"").Append(i).Append("\";\n");
        }
        sb.Append('\n');

        foreach (var e in enums.Values)
            EmitEnum(sb, e);

        foreach (var m in messages)
        {
            sb.Append("message ").Append(m.Name).Append(" {\n");
            foreach (var f in m.Fields)
            {
                sb.Append("  ");
                var fm = f.Model;
                var v = fm.Value;
                switch (fm.Shape)
                {
                    case FieldShape.Repeated:
                        sb.Append("repeated ").Append(TypeName(v, plan));
                        break;
                    case FieldShape.Map:
                        sb.Append("map<").Append(TypeName(fm.MapKey!, plan)).Append(", ").Append(TypeName(v, plan)).Append('>');
                        break;
                    default:
                        if (fm.IsNullable && HasExplicitPresenceKeyword(v.Kind))
                            sb.Append("optional ");
                        sb.Append(TypeName(v, plan));
                        break;
                }
                sb.Append(' ').Append(OutputPlanner.Sanitize(fm.Name)).Append(" = ").Append(f.Number).Append(';');
                var note = Note(v.Kind, fm.MapKey?.Kind);
                if (note is not null)
                    sb.Append(" // ").Append(note);
                sb.Append('\n');
            }
            sb.Append("}\n\n");
        }

        foreach (var svc in endpoints.GroupBy(e => e.Model.Service, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            sb.Append("service ").Append(svc.Key).Append(" {\n");
            foreach (var ep in svc.OrderBy(e => e.Model.Method, StringComparer.Ordinal))
            {
                var kind = ep.Model.Kind;
                sb.Append("  rpc ").Append(ep.Model.Method).Append(" (");
                if (kind is RpcKind.ClientStreaming or RpcKind.DuplexStreaming) sb.Append("stream ");
                sb.Append(ep.Model.RequestType.Length == 0 ? "google.protobuf.Empty" : plan.MessageName(ep.Model.RequestType));
                sb.Append(") returns (");
                if (kind is RpcKind.ServerStreaming or RpcKind.DuplexStreaming) sb.Append("stream ");
                sb.Append(ep.Model.ResponseType.Length == 0 ? "google.protobuf.Empty" : plan.MessageName(ep.Model.ResponseType));
                sb.Append(");\n");
            }
            sb.Append("}\n\n");
        }

        return sb.ToString().TrimEnd('\n') + "\n";
    }

    private static bool HasExplicitPresenceKeyword(ValueKind k)
        => k is not (ValueKind.Message or ValueKind.DateTime or ValueKind.DateTimeOffset or ValueKind.DateOnly
            or ValueKind.TimeSpan or ValueKind.TimeOnly);

    private static string? Note(ValueKind value, ValueKind? key)
    {
        string? N(ValueKind k) => k switch
        {
            ValueKind.Guid => "Guid as canonical \"D\" string",
            ValueKind.Decimal => "decimal as invariant-culture string",
            ValueKind.Char => "char as UTF-16 code unit",
            ValueKind.DateOnly => "DateOnly as midnight UTC",
            ValueKind.TimeOnly => "TimeOnly as duration since midnight",
            _ => null,
        };
        return N(value) ?? (key is { } k2 ? N(k2) : null);
    }

    public static string TypeName(ValueInfo v, OutputPlan plan) => v.Kind switch
    {
        ValueKind.Bool => "bool",
        ValueKind.Int32 => "int32",
        ValueKind.Int64 => "int64",
        ValueKind.UInt32 => "uint32",
        ValueKind.UInt64 => "uint64",
        ValueKind.Float => "float",
        ValueKind.Double => "double",
        ValueKind.Char => "uint32",
        ValueKind.String => "string",
        ValueKind.Bytes => "bytes",
        ValueKind.Guid => "string",
        ValueKind.Decimal => "string",
        ValueKind.DateTime or ValueKind.DateTimeOffset or ValueKind.DateOnly => "google.protobuf.Timestamp",
        ValueKind.TimeSpan or ValueKind.TimeOnly => "google.protobuf.Duration",
        ValueKind.Enum => plan.Enums.TryGetValue(v.RefKey, out var e) ? e.Name : "int32",
        ValueKind.Message => plan.MessageName(v.RefKey),
        _ => "bytes",
    };

    private static void EmitEnum(StringBuilder sb, ResolvedEnum e)
    {
        var prefix = UpperSnake(e.Name) + "_";
        var members = e.Model.Members.ToList();
        var zero = members.FirstOrDefault(m => m.Value == "0");
        var ordered = new List<(string Name, string Value)>();
        var names = new HashSet<string>(StringComparer.Ordinal);
        if (zero is null)
        {
            var unspecified = prefix + "UNSPECIFIED";
            while (members.Any(m => prefix + UpperSnake(m.Name) == unspecified))
                unspecified += "_";
            ordered.Add((unspecified, "0"));
            names.Add(unspecified);
        }
        else
        {
            members.Remove(zero);
            members.Insert(0, zero);
        }
        foreach (var m in members)
        {
            var name = prefix + UpperSnake(m.Name);
            while (!names.Add(name))
                name += "_";
            ordered.Add((name, m.Value));
        }

        sb.Append("enum ").Append(e.Name).Append(" {\n");
        if (ordered.Select(o => o.Value).Distinct(StringComparer.Ordinal).Count() != ordered.Count)
            sb.Append("  option allow_alias = true;\n");
        foreach (var (name, value) in ordered)
            sb.Append("  ").Append(name).Append(" = ").Append(value).Append(";\n");
        sb.Append("}\n\n");
    }

    /// <summary>PascalCase / camelCase → UPPER_SNAKE_CASE (proto enum value style).</summary>
    public static string UpperSnake(string name)
    {
        var s = OutputPlanner.Sanitize(name);
        var sb = new StringBuilder(s.Length + 8);
        for (var i = 0; i < s.Length; i++)
        {
            var c = s[i];
            if (char.IsUpper(c) && i > 0 && s[i - 1] != '_')
            {
                var prev = s[i - 1];
                var nextLower = i + 1 < s.Length && char.IsLower(s[i + 1]);
                if (char.IsLower(prev) || char.IsDigit(prev) || (char.IsUpper(prev) && nextLower))
                    sb.Append('_');
            }
            sb.Append(char.ToUpperInvariant(c));
        }
        return sb.ToString();
    }
}
