using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace KetPsi.Endpoints.Grpc.Generator;

/// <summary>
/// Pure protobuf wire codecs (no protobuf-net). Namespace: KetPsi.Endpoints.Grpc.
/// Supports scalars, enums, Guid, DateTime, TimeSpan, decimal, bytes, nested messages,
/// nullable value/reference types, and repeated fields.
/// </summary>
internal static class ProtoCodecEmitter
{
    public static void Emit(
        SourceProductionContext context,
        ImmutableArray<GrpcEndpointModel> endpoints,
        ImmutableArray<TypeConfigModel> typeConfigs,
        Compilation compilation)
    {
        var enriched = ProtoSchemaEmitter.ApplyTypeConfigFields(endpoints, typeConfigs);
        var messages = CollectMessages(enriched);
        if (messages.Count == 0)
            return;

        // Index by CLR name and simple message name for nested lookups
        var byClr = new Dictionary<string, MessageShape>(StringComparer.Ordinal);
        foreach (var m in messages)
        {
            byClr[m.ClrTypeName] = m;
            var simple = SimpleTypeName(m.ClrTypeName);
            if (!string.IsNullOrEmpty(simple) && !byClr.ContainsKey(simple))
                byClr[simple] = m;
            if (!string.IsNullOrEmpty(m.MessageName) && !byClr.ContainsKey(m.MessageName))
                byClr[m.MessageName] = m;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Buffers;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using KetPsi.Endpoints.Grpc.Wire;");
        sb.AppendLine("using Grpc.Core;");
        sb.AppendLine();
        sb.AppendLine("namespace KetPsi.Endpoints.Grpc");
        sb.AppendLine("{");
        sb.AppendLine("    public static partial class GeneratedProtoCodecs");
        sb.AppendLine("    {");
        sb.AppendLine("        public static void Register() { }");
        sb.AppendLine();

        var factories = BuildFactoryLookup(typeConfigs);
        foreach (var msg in messages.OrderBy(m => m.ClrTypeName, StringComparer.Ordinal))
            EmitMessageCodec(sb, msg, byClr, compilation, factories);

        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("GeneratedProtoCodecs.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static Dictionary<string, (string Method, string? DeclaringType)> BuildFactoryLookup(
        ImmutableArray<TypeConfigModel> typeConfigs)
    {
        var map = new Dictionary<string, (string Method, string? DeclaringType)>(StringComparer.Ordinal);
        void Index(string key, string method, string? declaring)
        {
            if (string.IsNullOrEmpty(key)) return;
            map[key] = (method, declaring);
        }

        foreach (var c in typeConfigs)
        {
            if (string.IsNullOrEmpty(c.FactoryMethodName))
                continue;
            var key = c.TargetTypeName ?? "";
            if (string.IsNullOrEmpty(key) || key == "IOpenProtoTypeConfiguration")
                continue;
            var method = c.FactoryMethodName!;
            var declaring = c.FactoryDeclaringTypeName;
            Index(key, method, declaring);

            // Strip global::
            var k = key.StartsWith("global::", StringComparison.Ordinal) ? key.Substring(8) : key;
            Index(k, method, declaring);

            // Simple name ResponseWrapper`1 / ResponseWrapper<>
            var lastDot = k.LastIndexOf('.');
            var simple = lastDot >= 0 ? k.Substring(lastDot + 1) : k;
            Index(simple, method, declaring);

            // Normalize open generic forms: Foo<T> / Foo`1 → Foo`1 and Foo
            var lt = simple.IndexOf('<');
            if (lt > 0)
            {
                var bare = simple.Substring(0, lt);
                Index(bare, method, declaring);
                // count commas for arity approx
                var arity = 1 + simple.Count(ch => ch == ',');
                Index(bare + "`" + arity, method, declaring);
            }
            var tick = simple.IndexOf('`');
            if (tick > 0)
            {
                Index(simple.Substring(0, tick), method, declaring);
            }
        }
        return map;
    }

    private static void EmitMessageCodec(
        StringBuilder sb,
        MessageShape msg,
        Dictionary<string, MessageShape> byClr,
        Compilation compilation,
        Dictionary<string, (string Method, string? DeclaringType)> factories)
    {
        var typeName = msg.ClrTypeName;
        if (IsForbiddenCodecClrName(typeName))
            return;
        var safe = Sanitize(msg.MessageName);
        var plan = ConstructionAnalyzer.Analyze(compilation, typeName, msg.Fields, factories);

        // Write
        sb.AppendLine($"        public static void Write_{safe}(ref ProtoWireWriter writer, {typeName} value)");
        sb.AppendLine("        {");
        if (msg.IsReferenceType)
            sb.AppendLine("            if (value is null) return;");
        foreach (var f in msg.Fields.OrderBy(x => x.Number))
            EmitWriteField(sb, f, byClr);
        sb.AppendLine("        }");
        sb.AppendLine();

        // Read — locals first, then construct (ctor / object initializer / parameterless+set)
        sb.AppendLine($"        public static {typeName} Read_{safe}(ref ProtoWireReader reader)");
        sb.AppendLine("        {");
        foreach (var f in msg.Fields.OrderBy(x => x.Number))
            EmitFieldLocal(sb, f);
        foreach (var f in msg.Fields.Where(x => x.Kind == FieldKind.Repeated && x.IsArray))
        {
            var acc = AccName(f.Name);
            sb.AppendLine($"            global::System.Collections.Generic.List<{f.ElementClrHint}>? {acc} = null;");
        }
        sb.AppendLine("            while (reader.TryReadTag(out var field, out var wireType))");
        sb.AppendLine("            {");
        sb.AppendLine("                switch (field)");
        sb.AppendLine("                {");
        foreach (var f in msg.Fields.OrderBy(x => x.Number))
            EmitReadCase(sb, f, byClr);
        sb.AppendLine("                    default: reader.SkipField(wireType); break;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        foreach (var f in msg.Fields.Where(x => x.Kind == FieldKind.Repeated && x.IsArray))
        {
            var acc = AccName(f.Name);
            var loc = LocalName(f.Name);
            sb.AppendLine($"            if ({acc} is not null) {loc} = {acc}.ToArray();");
        }
        EmitConstruction(sb, typeName, msg.Fields, plan);
        sb.AppendLine("        }");
        sb.AppendLine();

        // byte[] helpers — inline ref struct usage (no Func/Action)
        sb.AppendLine($"        public static byte[] Serialize_{safe}({typeName} value)");
        sb.AppendLine("        {");
        sb.AppendLine("            var buffer = new ArrayBufferWriter<byte>(128);");
        sb.AppendLine("            var writer = new ProtoWireWriter(buffer);");
        sb.AppendLine($"            Write_{safe}(ref writer, value);");
        sb.AppendLine("            writer.Dispose();");
        sb.AppendLine("            return buffer.WrittenSpan.ToArray();");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.AppendLine($"        public static {typeName} Deserialize_{safe}(byte[] payload)");
        sb.AppendLine("        {");
        sb.AppendLine("            var reader = new ProtoWireReader(payload);");
        sb.AppendLine($"            return Read_{safe}(ref reader);");
        sb.AppendLine("        }");
        sb.AppendLine();

        // Contextual marshaller: write into Kestrel buffer; read from ReadOnlySequence (single-segment fast path)
        sb.AppendLine($"        public static readonly Marshaller<{typeName}> Marshaller_{safe} = new Marshaller<{typeName}>(");
        sb.AppendLine("            static (arg, ctx) =>");
        sb.AppendLine("            {");
        sb.AppendLine($"                var w = new ProtoWireWriter(ctx.GetBufferWriter());");
        sb.AppendLine($"                Write_{safe}(ref w, arg);");
        sb.AppendLine("                ctx.Complete();");
        sb.AppendLine("            },");
        sb.AppendLine("            static ctx =>");
        sb.AppendLine("            {");
        sb.AppendLine("                var seq = ctx.PayloadAsReadOnlySequence();");
        sb.AppendLine("                if (seq.IsSingleSegment)");
        sb.AppendLine("                {");
        sb.AppendLine("                    var reader = new ProtoWireReader(seq.FirstSpan);");
        sb.AppendLine($"                    return Read_{safe}(ref reader);");
        sb.AppendLine("                }");
        sb.AppendLine("                // Multi-segment rare path");
        sb.AppendLine("                var rented = new byte[seq.Length];");
        sb.AppendLine("                seq.CopyTo(rented);");
        sb.AppendLine("                var reader2 = new ProtoWireReader(rented);");
        sb.AppendLine($"                return Read_{safe}(ref reader2);");
        sb.AppendLine("            });");
        sb.AppendLine();
    }

    private static void EmitWriteField(StringBuilder sb, ProtoFieldModel f, Dictionary<string, MessageShape> byClr)
    {
        var access = "value." + f.Name;
        var isNullable = f.IsNullable;
        var proto = f.ProtoType.Trim();
        var kind = f.Kind;

        if (kind == FieldKind.Map)
        {
            EmitWriteMapField(sb, f, access, byClr);
            return;
        }

        if (kind == FieldKind.Repeated)
        {
            sb.AppendLine($"            if ({access} is not null)");
            sb.AppendLine("            {");
            sb.AppendLine($"                foreach (var __item in {access})");
            sb.AppendLine("                {");
            EmitWriteOne(sb, f.Number, f.ElementProtoType, f.ElementClrHint, f.ElementKind, "__item", isNullable: false, byClr, "                    ");
            sb.AppendLine("                }");
            sb.AppendLine("            }");
            return;
        }

        EmitWriteOne(sb, f.Number, proto, f.ClrTypeHint, kind, access, isNullable, byClr, "            ");
    }

    private static void EmitWriteMapField(StringBuilder sb, ProtoFieldModel f, string access, Dictionary<string, MessageShape> byClr)
    {
        // map entries: repeated length-delimited messages with key=1, value=2
        sb.AppendLine($"            if ({access} is not null)");
        sb.AppendLine("            {");
        sb.AppendLine($"                foreach (var __kv in {access})");
        sb.AppendLine("                {");
        sb.AppendLine("                    var __entryBuf = new ArrayBufferWriter<byte>(32);");
        sb.AppendLine("                    var __ew = new ProtoWireWriter(__entryBuf);");
        EmitWriteOne(sb, 1, f.MapKeyProtoType, f.MapKeyClrHint, f.MapKeyKind, "__kv.Key", false, byClr, "                    ", "__ew");
        EmitWriteOne(sb, 2, f.ElementProtoType, f.ElementClrHint, f.ElementKind, "__kv.Value", false, byClr, "                    ", "__ew");
        sb.AppendLine("                    __ew.Dispose();");
        sb.AppendLine($"                    writer.WriteTag({f.Number}, ProtoWireType.LengthDelimited);");
        sb.AppendLine("                    writer.WriteLengthDelimitedBytes(__entryBuf.WrittenSpan);");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
    }

    private static void EmitWriteOne(
        StringBuilder sb, int number, string proto, string clrHint, FieldKind kind,
        string access, bool isNullable, Dictionary<string, MessageShape> byClr, string indent,
        string w = "writer")
    {
        void L(string s) => sb.Append(indent).AppendLine(s);

        MessageShape? nested = null;
        if (TryFindNested(byClr, clrHint, out nested) ||
            (kind == FieldKind.Message && TryFindNested(byClr, SimpleTypeName(clrHint), out nested)))
        {
            if (nested is null)
                return;
            var nestedSafe = Sanitize(nested.MessageName);
            if (isNullable)
            {
                L($"if ({access} is not null)");
                L("{");
                L($"    var __buf = new ArrayBufferWriter<byte>(64);");
                L($"    var __nw = new ProtoWireWriter(__buf);");
                L($"    Write_{nestedSafe}(ref __nw, {access});");
                L($"    __nw.Dispose();");
                L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                L("}");
            }
            else
            {
                L($"{{");
                L($"    var __buf = new ArrayBufferWriter<byte>(64);");
                L($"    var __nw = new ProtoWireWriter(__buf);");
                L($"    Write_{nestedSafe}(ref __nw, {access});");
                L($"    __nw.Dispose();");
                L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                L("}");
            }
            return;
        }

        switch (kind)
        {
            case FieldKind.Enum:
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    {w}.WriteTag({number}, ProtoWireType.Varint);");
                    L($"    {w}.WriteInt32((int){access}.Value);");
                    L("}");
                }
                else
                {
                    L($"{w}.WriteTag({number}, ProtoWireType.Varint);");
                    L($"{w}.WriteInt32((int){access});");
                }
                break;
            case FieldKind.Int32:
                WriteVarintScalar(L, number, access, isNullable, "WriteInt32", cast: null, w);
                break;
            case FieldKind.Int64:
                WriteVarintScalar(L, number, access, isNullable, "WriteInt64", cast: null, w);
                break;
            case FieldKind.UInt32:
                WriteVarintScalar(L, number, access, isNullable, "WriteUInt32", cast: null, w);
                break;
            case FieldKind.UInt64:
                WriteVarintScalar(L, number, access, isNullable, "WriteUInt64", cast: null, w);
                break;
            case FieldKind.Bool:
                WriteVarintScalar(L, number, access, isNullable, "WriteBool", cast: null, w);
                break;
            case FieldKind.Float:
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    {w}.WriteTag({number}, ProtoWireType.Fixed32);");
                    L($"    {w}.WriteFloat({access}.Value);");
                    L("}");
                }
                else
                {
                    L($"{w}.WriteTag({number}, ProtoWireType.Fixed32);");
                    L($"{w}.WriteFloat({access});");
                }
                break;
            case FieldKind.Double:
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    {w}.WriteTag({number}, ProtoWireType.Fixed64);");
                    L($"    {w}.WriteDouble({access}.Value);");
                    L("}");
                }
                else
                {
                    L($"{w}.WriteTag({number}, ProtoWireType.Fixed64);");
                    L($"{w}.WriteDouble({access});");
                }
                break;
            case FieldKind.String:
            {
                // char / char? encode as 1-char string; string as usual
                if (IsCharClr(clrHint))
                {
                    if (isNullable)
                    {
                        L($"if ({access}.HasValue)");
                        L("{");
                        L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    {w}.WriteString({access}.Value.ToString());");
                        L("}");
                    }
                    else
                    {
                        L($"{w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"{w}.WriteString({access}.ToString());");
                    }
                }
                else if (isNullable)
                {
                    L($"if ({access} is not null)");
                    L("{");
                    L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    {w}.WriteString({access});");
                    L("}");
                }
                else
                {
                    L($"{w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"{w}.WriteString({access} ?? string.Empty);");
                }
                break;
            }
            case FieldKind.Bytes:
                L($"if ({access} is not null)");
                L("{");
                L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                L($"    {w}.WriteBytes({access});");
                L("}");
                break;
            case FieldKind.Guid:
                // bytes (16) — Guid is not a protobuf scalar
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    {w}.WriteBytes({access}.Value.ToByteArray());");
                    L("}");
                }
                else
                {
                    L($"{w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"{w}.WriteBytes({access}.ToByteArray());");
                }
                break;
            case FieldKind.DateTime:
                // google.protobuf.Timestamp — DateTime and DateTimeOffset are different CLR types
                if (IsDateTimeOffsetClr(clrHint))
                {
                    if (isNullable)
                    {
                        L($"if ({access}.HasValue)");
                        L("{");
                        L($"    var __dto = {access}.Value;");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                    else
                    {
                        L($"{{");
                        L($"    var __dto = {access};");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                }
                else
                {
                    // System.DateTime
                    if (isNullable)
                    {
                        L($"if ({access}.HasValue)");
                        L("{");
                        L($"    var __dt = {access}.Value.Kind == DateTimeKind.Unspecified ? DateTime.SpecifyKind({access}.Value, DateTimeKind.Utc) : {access}.Value.ToUniversalTime();");
                        L($"    var __dto = new DateTimeOffset(__dt);");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                    else
                    {
                        L($"{{");
                        L($"    var __dt = {access}.Kind == DateTimeKind.Unspecified ? DateTime.SpecifyKind({access}, DateTimeKind.Utc) : {access}.ToUniversalTime();");
                        L($"    var __dto = new DateTimeOffset(__dt);");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                }
                break;
            case FieldKind.TimeSpan:
                // google.protobuf.Duration { int64 seconds=1; int32 nanos=2; }
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    var __ts = {access}.Value;");
                    L($"    var __sec = (long)__ts.TotalSeconds;");
                    L($"    var __nano = (int)((__ts.Ticks % TimeSpan.TicksPerSecond) * 100);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                    L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                    L($"    __nw.Dispose();");
                    L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                else
                {
                    L($"{{");
                    L($"    var __ts = {access};");
                    L($"    var __sec = (long)__ts.TotalSeconds;");
                    L($"    var __nano = (int)((__ts.Ticks % TimeSpan.TicksPerSecond) * 100);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                    L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                    L($"    __nw.Dispose();");
                    L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                break;
            case FieldKind.Decimal:
                // DecimalValue { int64 units=1; sfixed32 nanos=2; } — MS docs
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    var __dec = {access}.Value;");
                    L($"    var __units = decimal.ToInt64(__dec);");
                    L($"    var __nanos = decimal.ToInt32((__dec - __units) * 1_000_000_000m);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__units);");
                    L($"    if (__nanos != 0) {{ __nw.WriteTag(2, ProtoWireType.Fixed32); __nw.WriteFixed32(unchecked((uint)__nanos)); }}");
                    L($"    __nw.Dispose();");
                    L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                else
                {
                    L($"{{");
                    L($"    var __dec = {access};");
                    L($"    var __units = decimal.ToInt64(__dec);");
                    L($"    var __nanos = decimal.ToInt32((__dec - __units) * 1_000_000_000m);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__units);");
                    L($"    if (__nanos != 0) {{ __nw.WriteTag(2, ProtoWireType.Fixed32); __nw.WriteFixed32(unchecked((uint)__nanos)); }}");
                    L($"    __nw.Dispose();");
                    L($"    {w}.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    {w}.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                break;
            default:
                L($"// unhandled field kind {kind} ({proto})");
                break;
        }
    }

    private static void WriteVarintScalar(Action<string> L, int number, string access, bool isNullable, string method, string? cast, string w = "writer")
    {
        var arg = method switch
        {
            "WriteInt32" => $"(int)({access})",
            "WriteUInt32" => $"(uint)({access})",
            "WriteInt64" => $"(long)({access})",
            "WriteUInt64" => $"(ulong)({access})",
            "WriteBool" => access,
            _ => access
        };
        var argN = method switch
        {
            "WriteInt32" => $"(int)({access}.Value)",
            "WriteUInt32" => $"(uint)({access}.Value)",
            "WriteInt64" => $"(long)({access}.Value)",
            "WriteUInt64" => $"(ulong)({access}.Value)",
            "WriteBool" => $"{access}.Value",
            _ => $"{access}.Value"
        };

        if (isNullable)
        {
            L($"if ({access}.HasValue)");
            L("{");
            L($"    {w}.WriteTag({number}, ProtoWireType.Varint);");
            L($"    {w}.{method}({argN});");
            L("}");
        }
        else
        {
            L($"{w}.WriteTag({number}, ProtoWireType.Varint);");
            L($"{w}.{method}({arg});");
        }
    }

    private static void EmitReadCase(StringBuilder sb, ProtoFieldModel f, Dictionary<string, MessageShape> byClr)
    {
        var access = LocalName(f.Name);
        sb.AppendLine($"                    case {f.Number}:");

        if (f.Kind == FieldKind.Map)
        {
            EmitReadMapCase(sb, f, access, byClr);
            return;
        }

        if (f.Kind == FieldKind.Repeated)
        {
            var listTarget = f.IsArray ? AccName(f.Name) : access;
            if (f.IsArray)
                sb.AppendLine($"                        {listTarget} ??= new global::System.Collections.Generic.List<{f.ElementClrHint}>();");
            else
                sb.AppendLine($"                        {access} ??= new global::System.Collections.Generic.List<{f.ElementClrHint}>();");

            var packable = f.ElementKind is FieldKind.Int32 or FieldKind.Int64 or FieldKind.UInt32
                or FieldKind.UInt64 or FieldKind.Bool or FieldKind.Float or FieldKind.Double or FieldKind.Enum;
            if (packable)
            {
                sb.AppendLine("                        if (wireType == ProtoWireType.LengthDelimited)");
                sb.AppendLine("                        {");
                sb.AppendLine("                            var __pend = reader.BeginPacked();");
                sb.AppendLine("                            while (reader.Position < __pend)");
                sb.AppendLine("                            {");
                // one element without break
                EmitReadOneIntoPacked(sb, f.ElementKind, f.ElementClrHint, listTarget);
                sb.AppendLine("                            }");
                sb.AppendLine("                            break;");
                sb.AppendLine("                        }");
            }
            EmitReadOneInto(sb, f.ElementKind, f.ElementClrHint, f.ElementProtoType, access, byClr, listAdd: listTarget);
            return;
        }

        MessageShape? nested = null;
        if (TryFindNested(byClr, f.ClrTypeHint, out nested) ||
            (f.Kind == FieldKind.Message && TryFindNested(byClr, SimpleTypeName(f.ClrTypeHint), out nested)))
        {
            if (nested is null)
            {
                sb.AppendLine("                        reader.SkipField(wireType); break;");
                return;
            }
            sb.AppendLine("                    {");
            sb.AppendLine("                        var __sub = reader.ReadBytes();");
            sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
            sb.AppendLine($"                        {access} = Read_{Sanitize(nested.MessageName)}(ref __nr);");
            sb.AppendLine("                    }");
            sb.AppendLine("                        break;");
            return;
        }

        EmitReadOneInto(sb, f.Kind, f.ClrTypeHint, f.ProtoType, access, byClr, listAdd: null);
    }


    private static void EmitReadOneIntoPacked(StringBuilder sb, FieldKind kind, string clrHint, string listAdd)
    {
        switch (kind)
        {
            case FieldKind.Enum:
                sb.AppendLine($"                                {listAdd}.Add(({clrHint})reader.ReadInt32());");
                break;
            case FieldKind.Int32:
                sb.AppendLine($"                                {listAdd}.Add(reader.ReadInt32());");
                break;
            case FieldKind.Int64:
                sb.AppendLine($"                                {listAdd}.Add(reader.ReadInt64());");
                break;
            case FieldKind.UInt32:
                sb.AppendLine($"                                {listAdd}.Add(reader.ReadUInt32());");
                break;
            case FieldKind.UInt64:
                sb.AppendLine($"                                {listAdd}.Add(reader.ReadUInt64());");
                break;
            case FieldKind.Bool:
                sb.AppendLine($"                                {listAdd}.Add(reader.ReadBool());");
                break;
            case FieldKind.Float:
                sb.AppendLine($"                                {listAdd}.Add(reader.ReadFloat());");
                break;
            case FieldKind.Double:
                sb.AppendLine($"                                {listAdd}.Add(reader.ReadDouble());");
                break;
            default:
                break;
        }
    }

    private static void EmitReadOneInto(
        StringBuilder sb, FieldKind kind, string clrHint, string proto, string access,
        Dictionary<string, MessageShape> byClr, string? listAdd)
    {
        void AssignLine(string expr)
        {
            var castExpr = CastToClr(clrHint, expr);
            if (listAdd is not null)
                sb.AppendLine($"                        {listAdd}.Add({castExpr}); break;");
            else
                sb.AppendLine($"                        {access} = {castExpr}; break;");
        }

        switch (kind)
        {
            case FieldKind.Message:
            {
                MessageShape? nestedMsg = null;
                if (!TryFindNested(byClr, clrHint, out nestedMsg))
                    TryFindNested(byClr, SimpleTypeName(clrHint), out nestedMsg);
                if (nestedMsg is null)
                {
                    sb.AppendLine("                        reader.SkipField(wireType); break;");
                    break;
                }
                var nestedSafe = Sanitize(nestedMsg.MessageName);
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine($"                        var __nm = Read_{nestedSafe}(ref __nr);");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__nm);");
                else
                    sb.AppendLine($"                        {access} = __nm;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            }
            case FieldKind.Enum:
                // Enum underlying is int on the wire
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(({clrHint})reader.ReadInt32()); break;");
                else
                    sb.AppendLine($"                        {access} = ({clrHint})reader.ReadInt32(); break;");
                break;
            case FieldKind.Int32:
                AssignLine("reader.ReadInt32()");
                break;
            case FieldKind.Int64:
                AssignLine("reader.ReadInt64()");
                break;
            case FieldKind.UInt32:
                AssignLine("reader.ReadUInt32()");
                break;
            case FieldKind.UInt64:
                AssignLine("reader.ReadUInt64()");
                break;
            case FieldKind.Bool:
                AssignLine("reader.ReadBool()");
                break;
            case FieldKind.Float:
                AssignLine("reader.ReadFloat()");
                break;
            case FieldKind.Double:
                AssignLine("reader.ReadDouble()");
                break;
            case FieldKind.String:
                if (IsCharClr(clrHint))
                {
                    sb.AppendLine("                    {");
                    sb.AppendLine("                        var __cs = reader.ReadString();");
                    sb.AppendLine("                        var __ch = string.IsNullOrEmpty(__cs) ? default(char) : __cs[0];");
                    if (listAdd is not null)
                        sb.AppendLine($"                        {listAdd}.Add(__ch);");
                    else
                        sb.AppendLine($"                        {access} = __ch;");
                    sb.AppendLine("                    }");
                    sb.AppendLine("                        break;");
                }
                else
                {
                    AssignLine("reader.ReadString()");
                }
                break;
            case FieldKind.Bytes:
                AssignLine("reader.ReadBytes().ToArray()");
                break;
            case FieldKind.Guid:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __gb = reader.ReadBytes();");
                sb.AppendLine("                        var __gv = __gb.Length == 16 ? new Guid(__gb) : default;");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__gv);");
                else
                    sb.AppendLine($"                        {access} = __gv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            case FieldKind.DateTime:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine("                        long __sec = 0; int __nano = 0;");
                sb.AppendLine("                        while (__nr.TryReadTag(out var __f, out var __w))");
                sb.AppendLine("                        {");
                sb.AppendLine("                            if (__f == 1) __sec = __nr.ReadInt64();");
                sb.AppendLine("                            else if (__f == 2) __nano = __nr.ReadInt32();");
                sb.AppendLine("                            else __nr.SkipField(__w);");
                sb.AppendLine("                        }");
                if (IsDateTimeOffsetClr(clrHint))
                {
                    sb.AppendLine("                        var __dtv = DateTimeOffset.FromUnixTimeSeconds(__sec).AddTicks(__nano / 100);");
                }
                else
                {
                    sb.AppendLine("                        var __dtv = DateTimeOffset.FromUnixTimeSeconds(__sec).UtcDateTime.AddTicks(__nano / 100);");
                }
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__dtv);");
                else
                    sb.AppendLine($"                        {access} = __dtv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            case FieldKind.TimeSpan:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine("                        long __sec = 0; int __nano = 0;");
                sb.AppendLine("                        while (__nr.TryReadTag(out var __f, out var __w))");
                sb.AppendLine("                        {");
                sb.AppendLine("                            if (__f == 1) __sec = __nr.ReadInt64();");
                sb.AppendLine("                            else if (__f == 2) __nano = __nr.ReadInt32();");
                sb.AppendLine("                            else __nr.SkipField(__w);");
                sb.AppendLine("                        }");
                sb.AppendLine("                        var __tsv = TimeSpan.FromSeconds(__sec) + TimeSpan.FromTicks(__nano / 100);");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__tsv);");
                else
                    sb.AppendLine($"                        {access} = __tsv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            case FieldKind.Decimal:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine("                        long __units = 0; int __nanos = 0;");
                sb.AppendLine("                        while (__nr.TryReadTag(out var __f, out var __w))");
                sb.AppendLine("                        {");
                sb.AppendLine("                            if (__f == 1) __units = __nr.ReadInt64();");
                sb.AppendLine("                            else if (__f == 2) __nanos = unchecked((int)__nr.ReadFixed32());");
                sb.AppendLine("                            else __nr.SkipField(__w);");
                sb.AppendLine("                        }");
                sb.AppendLine("                        var __decv = __units + __nanos / 1_000_000_000m;");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__decv);");
                else
                    sb.AppendLine($"                        {access} = __decv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            default:
                sb.AppendLine("                        reader.SkipField(wireType); break;");
                break;
        }
    }


    private static void EmitReadMapCase(StringBuilder sb, ProtoFieldModel f, string access, Dictionary<string, MessageShape> byClr)
    {
        var keyClr = string.IsNullOrEmpty(f.MapKeyClrHint) ? "string" : f.MapKeyClrHint;
        var valClr = string.IsNullOrEmpty(f.ElementClrHint) ? "string" : f.ElementClrHint;
        sb.AppendLine($"                        {access} ??= new global::System.Collections.Generic.Dictionary<{keyClr}, {valClr}>();");
        sb.AppendLine("                    {");
        sb.AppendLine("                        var __sub = reader.ReadBytes();");
        sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
        sb.AppendLine($"                        {keyClr} __mapKey = default!;");
        sb.AppendLine($"                        {valClr} __mapVal = default!;");
        sb.AppendLine("                        while (__nr.TryReadTag(out var __mf, out var __mw))");
        sb.AppendLine("                        {");
        sb.AppendLine("                            if (__mf == 1)");
        sb.AppendLine("                            {");
        EmitReadScalarInto(sb, f.MapKeyKind, f.MapKeyClrHint, "__mapKey", "__nr", byClr, "                                ");
        sb.AppendLine("                            }");
        sb.AppendLine("                            else if (__mf == 2)");
        sb.AppendLine("                            {");
        EmitReadScalarInto(sb, f.ElementKind, f.ElementClrHint, "__mapVal", "__nr", byClr, "                                ");
        sb.AppendLine("                            }");
        sb.AppendLine("                            else __nr.SkipField(__mw);");
        sb.AppendLine("                        }");
        sb.AppendLine($"                        {access}[__mapKey] = __mapVal;");
        sb.AppendLine("                    }");
        sb.AppendLine("                        break;");
    }

    private static void EmitReadScalarInto(
        StringBuilder sb, FieldKind kind, string clrHint, string target, string readerVar,
        Dictionary<string, MessageShape> byClr, string indent)
    {
        void L(string s) => sb.Append(indent).AppendLine(s);
        switch (kind)
        {
            case FieldKind.String:
                if (IsCharClr(clrHint))
                {
                    L($"{{ var __cs = {readerVar}.ReadString(); {target} = string.IsNullOrEmpty(__cs) ? default : __cs[0]; }}");
                }
                else
                    L($"{target} = {readerVar}.ReadString();");
                break;
            case FieldKind.Bool:
                L($"{target} = {readerVar}.ReadBool();");
                break;
            case FieldKind.Int32:
                L($"{target} = {CastToClr(clrHint, readerVar + ".ReadInt32()")};");
                break;
            case FieldKind.Int64:
                L($"{target} = {CastToClr(clrHint, readerVar + ".ReadInt64()")};");
                break;
            case FieldKind.UInt32:
                L($"{target} = {CastToClr(clrHint, readerVar + ".ReadUInt32()")};");
                break;
            case FieldKind.UInt64:
                L($"{target} = {CastToClr(clrHint, readerVar + ".ReadUInt64()")};");
                break;
            case FieldKind.Float:
                L($"{target} = {readerVar}.ReadFloat();");
                break;
            case FieldKind.Double:
                L($"{target} = {readerVar}.ReadDouble();");
                break;
            case FieldKind.Enum:
                L($"{target} = ({clrHint}){readerVar}.ReadInt32();");
                break;
            case FieldKind.Bytes:
                L($"{target} = {readerVar}.ReadBytes().ToArray();");
                break;
            case FieldKind.Guid:
                L($"{{ var __gb = {readerVar}.ReadBytes(); {target} = __gb.Length == 16 ? new Guid(__gb) : default; }}");
                break;
            case FieldKind.Message:
            {
                MessageShape? nested = null;
                TryFindNested(byClr, clrHint, out nested);
                if (nested is null)
                    TryFindNested(byClr, SimpleTypeName(clrHint), out nested);
                if (nested is not null)
                {
                    L($"{{ var __ms = {readerVar}.ReadBytes(); var __mr = new ProtoWireReader(__ms); {target} = Read_{Sanitize(nested.MessageName)}(ref __mr); }}");
                }
                else
                    L($"{readerVar}.SkipField(ProtoWireType.LengthDelimited);");
                break;
            }
            default:
                L($"{readerVar}.SkipField(ProtoWireType.Varint);");
                break;
        }
    }


    private static bool IsForbiddenCodecClrName(string clr)
    {
        if (string.IsNullOrEmpty(clr)) return true;
        if (clr.StartsWith("global::", StringComparison.Ordinal))
            clr = clr.Substring("global::".Length);
        if (clr is "System.Type" or "System.Reflection.TypeInfo" or "System.Reflection.Assembly"
            or "System.Reflection.Module" or "System.Reflection.MemberInfo"
            or "System.Reflection.MethodInfo" or "System.Reflection.PropertyInfo"
            or "System.Reflection.FieldInfo" or "System.Reflection.ConstructorInfo"
            or "System.Reflection.ParameterInfo" or "System.Reflection.EventInfo"
            or "System.Delegate" or "System.MulticastDelegate" or "System.Enum" or "System.ValueType"
            or "System.Array" or "System.Object")
            return true;
        if (clr.StartsWith("System.Reflection.", StringComparison.Ordinal))
            return true;
        return false;
    }

    private static string LocalName(string propName) => "__p_" + propName;

    /// <summary>
    /// Empty repeated/map fields were never present on the wire — emit empty collections instead of null.
    /// </summary>
    private static string CoalesceExpr(ProtoFieldModel f)
    {
        var loc = LocalName(f.Name);
        if (f.Kind == FieldKind.Repeated)
        {
            if (f.IsArray)
            {
                var elem = string.IsNullOrEmpty(f.ElementClrHint) ? "object" : f.ElementClrHint;
                return $"{loc} ?? System.Array.Empty<{elem}>()";
            }
            return $"{loc} ?? new global::System.Collections.Generic.List<{f.ElementClrHint}>()";
        }
        if (f.Kind == FieldKind.Map)
        {
            var k = string.IsNullOrEmpty(f.MapKeyClrHint) ? "string" : f.MapKeyClrHint;
            var v = string.IsNullOrEmpty(f.ElementClrHint) ? "string" : f.ElementClrHint;
            return $"{loc} ?? new global::System.Collections.Generic.Dictionary<{k}, {v}>()";
        }
        return loc;
    }

    private static void EmitFieldLocal(StringBuilder sb, ProtoFieldModel f)
    {
        var loc = LocalName(f.Name);
        var ty = LocalClrType(f);
        // reference types and nullables: default!; value types: default
        if (NeedsDefaultBang(f, ty))
            sb.AppendLine($"            {ty} {loc} = default!;");
        else
            sb.AppendLine($"            {ty} {loc} = default;");
    }

    private static string LocalClrType(ProtoFieldModel f)
    {
        if (f.Kind == FieldKind.Map)
        {
            var k = string.IsNullOrEmpty(f.MapKeyClrHint) ? "string" : f.MapKeyClrHint;
            var v = string.IsNullOrEmpty(f.ElementClrHint) ? "string" : f.ElementClrHint;
            return $"global::System.Collections.Generic.Dictionary<{k}, {v}>?";
        }
        if (f.Kind == FieldKind.Repeated)
        {
            if (f.IsArray)
                return (string.IsNullOrEmpty(f.ElementClrHint) ? "object" : f.ElementClrHint) + "[]?";
            return $"global::System.Collections.Generic.List<{f.ElementClrHint}>?";
        }
        if (!string.IsNullOrEmpty(f.ClrTypeHint))
        {
            var c = f.ClrTypeHint;
            // Nullable value types + enums must keep '?' so all-null round-trips stay null
            if (f.IsNullable && !c.EndsWith("?", StringComparison.Ordinal) &&
                (IsValueTypeHint(c) || f.Kind == FieldKind.Enum || f.Kind == FieldKind.Guid
                 || f.Kind == FieldKind.DateTime || f.Kind == FieldKind.TimeSpan || f.Kind == FieldKind.Decimal))
                return c + "?";
            return c;
        }
        return "object";
    }

    private static bool IsValueTypeHint(string clr)
    {
        switch (clr)
        {
            case "bool": case "byte": case "sbyte": case "short": case "ushort":
            case "int": case "uint": case "long": case "ulong":
            case "float": case "double": case "decimal": case "char":
            case "System.Guid": case "Guid":
            case "System.DateTime": case "DateTime":
            case "System.DateTimeOffset": case "DateTimeOffset":
            case "System.TimeSpan": case "TimeSpan":
            case "nint": case "nuint": case "System.IntPtr": case "System.UIntPtr":
                return true;
            default:
                // enums and other value types often unqualified names — treat non-namespace simple names carefully
                return false;
        }
    }

    private static bool NeedsDefaultBang(ProtoFieldModel f, string ty)
        => ty.EndsWith("?", StringComparison.Ordinal)
           || ty == "string"
           || f.Kind is FieldKind.Message or FieldKind.Bytes or FieldKind.String
           || (!IsValueTypeHint(f.ClrTypeHint) && f.Kind != FieldKind.Enum && f.Kind != FieldKind.Unknown);

    private static void EmitConstruction(
        StringBuilder sb,
        string typeName,
        System.Collections.Generic.IReadOnlyList<ProtoFieldModel> fields,
        ConstructionPlan plan)
    {
        switch (plan.Kind)
        {
            case ConstructionKind.Factory:
            {
                var args = new List<string>();
                foreach (var n in plan.CtorParameterPropertyNames)
                {
                    var field = fields.FirstOrDefault(x => x.Name == n);
                    args.Add(field is null ? LocalName(n) : CoalesceExpr(field));
                }
                var decl = plan.FactoryDeclaringTypeName;
                if (string.IsNullOrEmpty(decl))
                    decl = typeName;
                // Prefer closed type's static method; declaring type may be open/helper FQN
                sb.AppendLine($"            return {decl}.{plan.FactoryMethodName}({string.Join(", ", args)});");
                break;
            }
            case ConstructionKind.Constructor:
            {
                var args = new List<string>();
                foreach (var n in plan.CtorParameterPropertyNames)
                {
                    if (n is "default" or "default!")
                    {
                        args.Add("default");
                        continue;
                    }
                    var field = fields.FirstOrDefault(x => x.Name == n);
                    args.Add(field is null ? LocalName(n) : CoalesceExpr(field));
                }
                sb.AppendLine($"            return new {typeName}({string.Join(", ", args)});");
                break;
            }
            case ConstructionKind.ObjectInitializer:
            {
                sb.AppendLine($"            return new {typeName}");
                sb.AppendLine("            {");
                foreach (var f in fields.OrderBy(x => x.Number))
                    sb.AppendLine($"                {f.Name} = {CoalesceExpr(f)},");
                sb.AppendLine("            };");
                break;
            }
            default: // ParameterlessThenSet
            {
                sb.AppendLine($"            var value = new {typeName}();");
                foreach (var f in fields.OrderBy(x => x.Number))
                {
                    if (plan.SettableProperties.Count > 0 && !plan.SettableProperties.Contains(f.Name))
                        continue;
                    sb.AppendLine($"            value.{f.Name} = {CoalesceExpr(f)};");
                }
                sb.AppendLine("            return value;");
                break;
            }
        }
    }


    private static string AccName(string propName)
        => "__acc_" + propName;

    private static bool IsDateTimeOffsetClr(string clrHint)
    {
        if (string.IsNullOrEmpty(clrHint)) return false;
        var s = clrHint.Trim();
        if (s.EndsWith("?", StringComparison.Ordinal))
            s = s.Substring(0, s.Length - 1);
        return s == "DateTimeOffset"
               || s == "System.DateTimeOffset"
               || s.EndsWith(".DateTimeOffset", StringComparison.Ordinal);
    }

    private static bool IsCharClr(string clrHint)
    {
        if (string.IsNullOrEmpty(clrHint)) return false;
        var s = clrHint.Trim();
        return s == "char" || s == "Char" || s == "System.Char"
            || s == "char?" || s == "System.Char?" || s.EndsWith(".Char", StringComparison.Ordinal);
    }

    /// <summary>
    /// Narrow/widen wire values to the property CLR type (byte, sbyte, short, ushort, nint, nuint, …).
    /// </summary>
    private static string CastToClr(string clrHint, string expr)
    {
        if (string.IsNullOrEmpty(clrHint))
            return expr;

        var s = clrHint.Trim();
        // strip nullable annotation from type name for cast target
        if (s.EndsWith("?", StringComparison.Ordinal))
            s = s.Substring(0, s.Length - 1);

        // global:: prefix types
        var core = s;
        if (core.StartsWith("global::", StringComparison.Ordinal))
            core = core.Substring("global::".Length);

        switch (core)
        {
            case "byte":
            case "Byte":
            case "System.Byte":
                return $"(byte)({expr})";
            case "sbyte":
            case "SByte":
            case "System.SByte":
                return $"(sbyte)({expr})";
            case "short":
            case "Int16":
            case "System.Int16":
                return $"(short)({expr})";
            case "ushort":
            case "UInt16":
            case "System.UInt16":
                return $"(ushort)({expr})";
            case "int":
            case "Int32":
            case "System.Int32":
                return $"(int)({expr})";
            case "uint":
            case "UInt32":
            case "System.UInt32":
                return $"(uint)({expr})";
            case "long":
            case "Int64":
            case "System.Int64":
                return $"(long)({expr})";
            case "ulong":
            case "UInt64":
            case "System.UInt64":
                return $"(ulong)({expr})";
            case "nint":
            case "IntPtr":
            case "System.IntPtr":
                return $"(nint)({expr})";
            case "nuint":
            case "UIntPtr":
            case "System.UIntPtr":
                return $"(nuint)({expr})";
            case "float":
            case "Single":
            case "System.Single":
                return $"(float)({expr})";
            case "double":
            case "Double":
            case "System.Double":
                return $"(double)({expr})";
            default:
                // string, byte[], Guid, custom — no cast (or identity)
                return expr;
        }
    }

    private static bool TryFindNested(Dictionary<string, MessageShape> byClr, string hint, out MessageShape? nested)
    {
        nested = null;
        if (string.IsNullOrEmpty(hint) || byClr.Count == 0)
            return false;

        var normalized = NormalizeClrTypeName(hint);
        if (byClr.TryGetValue(normalized, out nested))
            return true;
        if (byClr.TryGetValue(hint, out nested))
            return true;

        foreach (var m in byClr.Values)
        {
            if (MatchNested(m, hint) || MatchNested(m, normalized))
            {
                nested = m;
                return true;
            }
        }

        var simple = SimpleTypeName(normalized);
        if (!string.IsNullOrEmpty(simple) && simple != normalized)
        {
            foreach (var m in byClr.Values)
            {
                if (string.Equals(m.MessageName, simple, StringComparison.Ordinal) ||
                    string.Equals(Sanitize(m.MessageName), Sanitize(simple), StringComparison.Ordinal))
                {
                    nested = m;
                    return true;
                }
            }
        }

        nested = null;
        return false;
    }

    private static bool MatchNested(MessageShape m, string hint)
    {
        if (string.IsNullOrEmpty(hint)) return false;
        var h = NormalizeClrTypeName(hint);
        return string.Equals(m.MessageName, hint, StringComparison.Ordinal)
               || string.Equals(m.MessageName, h, StringComparison.Ordinal)
               || string.Equals(m.ClrTypeName, h, StringComparison.Ordinal)
               || m.ClrTypeName.EndsWith("." + h, StringComparison.Ordinal)
               || m.ClrTypeName.EndsWith("+" + h, StringComparison.Ordinal)
               || m.ClrTypeName.EndsWith("." + SimpleTypeName(h), StringComparison.Ordinal);
    }

    private static List<MessageShape> CollectMessages(ImmutableArray<GrpcEndpointModel> endpoints)
    {
        // Key by normalized CLR type so NestedItem from multiple parents is registered once.
        var byClr = new Dictionary<string, MessageShape>(StringComparer.Ordinal);
        foreach (var ep in endpoints)
        {
            Add(byClr, ep.RequestTypeName, ep.RequestMessageName, ep.RequestFields, isRef: true);
            Add(byClr, UnwrapTask(ep.ResponseTypeName), ep.ResponseMessageName, ep.ResponseFields, isRef: true);
            if (!ep.NestedMessages.IsDefaultOrEmpty)
            {
                foreach (var n in ep.NestedMessages)
                    Add(byClr, n.ClrTypeName, n.MessageName, n.Fields, n.IsReferenceType);
            }
        }

        // Second pass: collapse by sanitized message name (Write_NestedItem / Marshaller_NestedItem).
        // Different CLR string forms of the same type must not emit duplicate members.
        var bySafeName = new Dictionary<string, MessageShape>(StringComparer.Ordinal);
        foreach (var shape in byClr.Values.Where(m => !string.IsNullOrEmpty(m.ClrTypeName) && m.Fields.Count > 0))
        {
            var safe = Sanitize(shape.MessageName);
            if (!bySafeName.TryGetValue(safe, out var existing))
            {
                bySafeName[safe] = shape;
                continue;
            }
            // Merge any missing fields from the duplicate registration
            foreach (var f in shape.Fields)
            {
                if (existing.Fields.All(x => x.Number != f.Number && x.Name != f.Name))
                    existing.Fields.Add(f);
            }
            // Prefer longer / more qualified CLR name for nested lookup
            if (shape.ClrTypeName.Length > existing.ClrTypeName.Length)
                existing.ClrTypeName = shape.ClrTypeName;
        }

        return bySafeName.Values.ToList();
    }

    private static void Add(
        Dictionary<string, MessageShape> map, string clrType, string messageName,
        ImmutableArray<ProtoFieldModel> fields, bool isRef)
    {
        clrType = NormalizeClrTypeName(UnwrapTask(clrType));
        if (string.IsNullOrEmpty(clrType) || fields.IsDefaultOrEmpty) return;
        if (!map.TryGetValue(clrType, out var shape))
        {
            shape = new MessageShape(clrType, string.IsNullOrEmpty(messageName) ? SimpleTypeName(clrType) : messageName, new List<ProtoFieldModel>(), isRef);
            map[clrType] = shape;
        }
        foreach (var f in fields)
            if (shape.Fields.All(x => x.Number != f.Number))
                shape.Fields.Add(f);
    }

    /// <summary>Strip global:: and normalize whitespace so the same type is one dictionary key.</summary>
    private static string NormalizeClrTypeName(string typeName)
    {
        if (string.IsNullOrEmpty(typeName)) return typeName;
        typeName = typeName.Trim();
        const string globalPrefix = "global::";
        if (typeName.StartsWith(globalPrefix, StringComparison.Ordinal))
            typeName = typeName.Substring(globalPrefix.Length);
        // Nullable annotation may appear as trailing '?' (e.g. NestedItem?)
        if (typeName.EndsWith("?", StringComparison.Ordinal))
            typeName = typeName.Substring(0, typeName.Length - 1);
        return typeName;
    }

    private static string SimpleTypeName(string clrType)
    {
        if (string.IsNullOrEmpty(clrType)) return "Message";
        var s = clrType;
        var gen = s.IndexOf('<');
        if (gen >= 0) s = s.Substring(0, gen);
        var plus = s.LastIndexOf('+');
        if (plus >= 0) return s.Substring(plus + 1);
        var dot = s.LastIndexOf('.');
        return dot >= 0 ? s.Substring(dot + 1) : s;
    }

    private static string UnwrapTask(string typeName)
    {
        if (string.IsNullOrEmpty(typeName)) return typeName;
        foreach (var prefix in new[]
                 {
                     "global::System.Threading.Tasks.Task<", "System.Threading.Tasks.Task<",
                     "global::System.Threading.Tasks.ValueTask<", "System.Threading.Tasks.ValueTask<"
                 })
        {
            var idx = typeName.IndexOf(prefix, StringComparison.Ordinal);
            if (idx >= 0)
            {
                var start = idx + prefix.Length;
                var end = typeName.LastIndexOf('>');
                if (end > start) return typeName.Substring(start, end - start).Trim();
            }
        }
        return typeName;
    }

    private static string Sanitize(string name)
    {
        if (string.IsNullOrEmpty(name)) return "Message";
        var chars = name.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray();
        return new string(chars);
    }


    private enum ConstructionKind
    {
        ParameterlessThenSet = 0,
        ObjectInitializer = 1,
        Constructor = 2,
        Factory = 3
    }

    private sealed class ConstructionPlan
    {
        public ConstructionKind Kind { get; }
        public System.Collections.Immutable.ImmutableArray<string> CtorParameterPropertyNames { get; }
        public System.Collections.Generic.HashSet<string> SettableProperties { get; }
        public string? FactoryMethodName { get; }
        public string? FactoryDeclaringTypeName { get; }

        private ConstructionPlan(
            ConstructionKind kind,
            System.Collections.Immutable.ImmutableArray<string> ctorParams,
            System.Collections.Generic.HashSet<string> settable,
            string? factoryMethod = null,
            string? factoryDeclaringType = null)
        {
            Kind = kind;
            CtorParameterPropertyNames = ctorParams;
            SettableProperties = settable;
            FactoryMethodName = factoryMethod;
            FactoryDeclaringTypeName = factoryDeclaringType;
        }

        public static ConstructionPlan ParameterlessSet(System.Collections.Generic.HashSet<string> settable)
            => new(ConstructionKind.ParameterlessThenSet, System.Collections.Immutable.ImmutableArray<string>.Empty, settable);

        public static ConstructionPlan ObjectInit()
            => new(ConstructionKind.ObjectInitializer, System.Collections.Immutable.ImmutableArray<string>.Empty, new System.Collections.Generic.HashSet<string>());

        public static ConstructionPlan Ctor(System.Collections.Immutable.ImmutableArray<string> paramProps)
            => new(ConstructionKind.Constructor, paramProps, new System.Collections.Generic.HashSet<string>());

        public static ConstructionPlan Factory(string methodName, string? declaringType, System.Collections.Immutable.ImmutableArray<string> argProps)
            => new(ConstructionKind.Factory, argProps, new System.Collections.Generic.HashSet<string>(), methodName, declaringType);
    }

    /// <summary>
    /// Chooses how to build a message type after fields are read into locals:
    /// 1) Public ctor whose parameters match property names (records primary ctor, private-set classes)
    /// 2) Object initializer when parameterless ctor + public set/init on all fields
    /// 3) Parameterless ctor + assign public setters only
    /// </summary>
    private static class ConstructionAnalyzer
    {
        public static ConstructionPlan Analyze(
            Compilation compilation,
            string clrTypeName,
            System.Collections.Generic.IReadOnlyList<ProtoFieldModel> fields,
            Dictionary<string, (string Method, string? DeclaringType)>? factories = null)
        {
            var fieldNames = fields.Select(f => f.Name).ToList();
            // Factory from IProtoTypeConfiguration / IOpenProtoTypeConfiguration wins
            if (factories is not null && TryResolveFactory(clrTypeName, factories, out var facMethod, out var facDecl))
            {
                var ordered = fields.OrderBy(f => f.Number).Select(f => f.Name).ToImmutableArray();
                return ConstructionPlan.Factory(facMethod, facDecl, ordered);
            }

            var type = ResolveType(compilation, clrTypeName);
            if (type is null)
            {
                // Fallback: classic mutable POCO
                return ConstructionPlan.ParameterlessSet(new HashSet<string>(fieldNames, StringComparer.Ordinal));
            }

            var props = type.GetMembers()
                .OfType<IPropertySymbol>()
                .Where(p => !p.IsStatic && p.GetMethod is not null)
                .ToList();

            var publicCtors = type.InstanceConstructors
                .Where(c => c.DeclaredAccessibility == Accessibility.Public && !c.IsStatic)
                .ToList();

            // Prefer parameterized ctor (primary record ctor / explicit ctor) with name-matched params
            ConstructionPlan? bestCtor = null;
            var bestScore = -1;
            foreach (var ctor in publicCtors.Where(c => c.Parameters.Length > 0))
            {
                var mapped = new List<string>();
                var ok = true;
                foreach (var param in ctor.Parameters)
                {
                    var prop = props.FirstOrDefault(p =>
                        string.Equals(p.Name, param.Name, StringComparison.OrdinalIgnoreCase));
                    if (prop is null)
                    {
                        if (param.HasExplicitDefaultValue)
                        {
                            mapped.Add("default!");
                            continue;
                        }
                        ok = false;
                        break;
                    }
                    mapped.Add(prop.Name);
                }
                if (!ok)
                    continue;
                var score = mapped.Count(m => m != "default!");
                if (score > bestScore)
                {
                    bestScore = score;
                    bestCtor = ConstructionPlan.Ctor(mapped.ToImmutableArray());
                }
            }
            if (bestCtor is not null && bestScore > 0)
                return bestCtor;

            var paramless = publicCtors.FirstOrDefault(c => c.Parameters.Length == 0);
            if (paramless is not null)
            {
                var settable = new HashSet<string>(StringComparer.Ordinal);
                var allInitOrPublicSet = true;
                foreach (var name in fieldNames)
                {
                    var prop = props.FirstOrDefault(p => p.Name == name);
                    if (prop?.SetMethod is null || prop.SetMethod.DeclaredAccessibility != Accessibility.Public)
                    {
                        allInitOrPublicSet = false;
                        continue;
                    }
                    settable.Add(name);
                }

                if (allInitOrPublicSet && settable.Count == fieldNames.Count)
                    return ConstructionPlan.ObjectInit();

                if (settable.Count > 0)
                    return ConstructionPlan.ParameterlessSet(settable);

                // parameterless but nothing settable — still try object initializer (may fail at compile for private set)
                return ConstructionPlan.ObjectInit();
            }

            // No public parameterless ctor — last attempt: any public ctor with all params matchable
            foreach (var ctor in publicCtors.OrderByDescending(c => c.Parameters.Length))
            {
                var mapped = new List<string>();
                var ok = true;
                foreach (var param in ctor.Parameters)
                {
                    var prop = props.FirstOrDefault(p => string.Equals(p.Name, param.Name, StringComparison.OrdinalIgnoreCase));
                    if (prop is null) { ok = false; break; }
                    mapped.Add(prop.Name);
                }
                if (ok)
                    return ConstructionPlan.Ctor(mapped.ToImmutableArray());
            }

            return ConstructionPlan.ParameterlessSet(new HashSet<string>(fieldNames, StringComparer.Ordinal));
        }

        private static bool TryResolveFactory(
            string clrTypeName,
            Dictionary<string, (string Method, string? DeclaringType)> factories,
            out string method,
            out string? declaringType)
        {
            method = "";
            declaringType = null;
            if (string.IsNullOrEmpty(clrTypeName))
                return false;

            var candidates = new List<string> { clrTypeName };
            var n = clrTypeName.Trim();
            if (n.StartsWith("global::", StringComparison.Ordinal))
                n = n.Substring("global::".Length);
            candidates.Add(n);

            // ResponseWrapper<Foo> → ResponseWrapper`1, ResponseWrapper, Namespace.ResponseWrapper`1
            var lt = n.IndexOf('<');
            if (lt > 0)
            {
                var before = n.Substring(0, lt);
                var after = n.Substring(lt);
                var arity = 1 + after.Count(ch => ch == ',');
                candidates.Add(before + "`" + arity);
                candidates.Add(before);
                var dot = before.LastIndexOf('.');
                if (dot >= 0)
                {
                    var bare = before.Substring(dot + 1);
                    candidates.Add(bare);
                    candidates.Add(bare + "`" + arity);
                }
            }

            var simple = SimpleTypeName(n);
            if (!string.IsNullOrEmpty(simple))
            {
                candidates.Add(simple);
                var slt = simple.IndexOf('<');
                if (slt > 0)
                {
                    var bare = simple.Substring(0, slt);
                    candidates.Add(bare);
                    candidates.Add(bare + "`1");
                }
            }

            foreach (var c in candidates)
            {
                if (factories.TryGetValue(c, out var fac))
                {
                    method = fac.Method;
                    declaringType = fac.DeclaringType;
                    // When declaring type is null, call on the concrete closed type name
                    if (string.IsNullOrEmpty(declaringType))
                        declaringType = n.StartsWith("global::") ? n : "global::" + n.Replace('+', '.');
                    return true;
                }
            }
            return false;
        }

        private static INamedTypeSymbol? ResolveType(Compilation compilation, string clrTypeName)
        {
            if (string.IsNullOrEmpty(clrTypeName))
                return null;
            var name = clrTypeName.Trim();
            if (name.StartsWith("global::", StringComparison.Ordinal))
                name = name.Substring("global::".Length);

            var byMetadata = compilation.GetTypeByMetadataName(name);
            if (byMetadata is not null)
                return byMetadata;

            // Try with + for nested types already using .
            // Search among referenced symbols — fallback scan is expensive; try common replacements
            byMetadata = compilation.GetTypeByMetadataName(name.Replace('+', '.'));
            if (byMetadata is not null)
                return byMetadata;

            // Last resort: match by display string among source-defined types is not available without visit.
            // Visitors: walk global namespace shallow for exact display match
            return FindByDisplayName(compilation.GlobalNamespace, name, clrTypeName);
        }

        private static INamedTypeSymbol? FindByDisplayName(INamespaceSymbol ns, string name, string original)
        {
            foreach (var type in ns.GetTypeMembers())
            {
                var d = type.ToDisplayString();
                if (d == name || d == original || type.Name == SimpleTypeName(name))
                {
                    if (!type.IsGenericType || d == name || d == original)
                        return type;
                }
                foreach (var nested in type.GetTypeMembers())
                {
                    var nd = nested.ToDisplayString();
                    if (nd == name || nd == original)
                        return nested;
                }
            }
            foreach (var child in ns.GetNamespaceMembers())
            {
                var found = FindByDisplayName(child, name, original);
                if (found is not null)
                    return found;
            }
            return null;
        }
    }


        private sealed class MessageShape
    {
        public string ClrTypeName { get; set; }
        public string MessageName { get; }
        public List<ProtoFieldModel> Fields { get; }
        public bool IsReferenceType { get; }
        public MessageShape(string clr, string msg, List<ProtoFieldModel> fields, bool isRef)
        {
            ClrTypeName = clr;
            MessageName = string.IsNullOrEmpty(msg) ? "Message" : msg;
            Fields = fields;
            IsReferenceType = isRef;
        }
    }
