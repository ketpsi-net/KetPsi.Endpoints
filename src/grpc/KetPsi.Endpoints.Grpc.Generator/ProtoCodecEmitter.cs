using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace KetPsi.Endpoints.Grpc.Generator;

/// <summary>
/// Pure protobuf wire codecs (no protobuf-net). Namespace: KetPsi.Endpoints.Grpc.
/// Supports scalars, enums, Guid, DateTime, TimeSpan, decimal, bytes, nested messages,
/// nullable value/reference types, and repeated fields.
/// </summary>
internal static class ProtoCodecEmitter
{
    public static void Emit(
        SourceProductionContext context,
        ImmutableArray<GrpcEndpointModel> endpoints,
        ImmutableArray<TypeConfigModel> typeConfigs)
    {
        var enriched = ProtoSchemaEmitter.ApplyTypeConfigFields(endpoints, typeConfigs);
        var messages = CollectMessages(enriched);
        if (messages.Count == 0)
            return;

        // Index by CLR name and simple message name for nested lookups
        var byClr = new Dictionary<string, MessageShape>(StringComparer.Ordinal);
        foreach (var m in messages)
        {
            byClr[m.ClrTypeName] = m;
            var simple = SimpleTypeName(m.ClrTypeName);
            if (!string.IsNullOrEmpty(simple) && !byClr.ContainsKey(simple))
                byClr[simple] = m;
            if (!string.IsNullOrEmpty(m.MessageName) && !byClr.ContainsKey(m.MessageName))
                byClr[m.MessageName] = m;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Buffers;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using KetPsi.Endpoints.Grpc.Wire;");
        sb.AppendLine("using Grpc.Core;");
        sb.AppendLine();
        sb.AppendLine("namespace KetPsi.Endpoints.Grpc");
        sb.AppendLine("{");
        sb.AppendLine("    public static partial class GeneratedProtoCodecs");
        sb.AppendLine("    {");
        sb.AppendLine("        public static void Register() { }");
        sb.AppendLine();

        foreach (var msg in messages.OrderBy(m => m.ClrTypeName, StringComparer.Ordinal))
            EmitMessageCodec(sb, msg, byClr);

        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("GeneratedProtoCodecs.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void EmitMessageCodec(StringBuilder sb, MessageShape msg, Dictionary<string, MessageShape> byClr)
    {
        var typeName = msg.ClrTypeName;
        var safe = Sanitize(msg.MessageName);

        // Write
        sb.AppendLine($"        public static void Write_{safe}(ref ProtoWireWriter writer, {typeName} value)");
        sb.AppendLine("        {");
        if (msg.IsReferenceType)
            sb.AppendLine("            if (value is null) return;");
        foreach (var f in msg.Fields.OrderBy(x => x.Number))
            EmitWriteField(sb, f, byClr);
        sb.AppendLine("        }");
        sb.AppendLine();

        // Read
        sb.AppendLine($"        public static {typeName} Read_{safe}(ref ProtoWireReader reader)");
        sb.AppendLine("        {");
        sb.AppendLine($"            var value = new {typeName}();");
        // Accumulators for array (T[]) repeated fields — cannot use List.Add on T[]
        foreach (var f in msg.Fields.Where(x => x.Kind == FieldKind.Repeated && x.IsArray))
        {
            var acc = AccName(f.Name);
            sb.AppendLine($"            global::System.Collections.Generic.List<{f.ElementClrHint}>? {acc} = null;");
        }
        sb.AppendLine("            while (reader.TryReadTag(out var field, out var wireType))");
        sb.AppendLine("            {");
        sb.AppendLine("                switch (field)");
        sb.AppendLine("                {");
        foreach (var f in msg.Fields.OrderBy(x => x.Number))
            EmitReadCase(sb, f, byClr);
        sb.AppendLine("                    default: reader.SkipField(wireType); break;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        foreach (var f in msg.Fields.Where(x => x.Kind == FieldKind.Repeated && x.IsArray))
        {
            var acc = AccName(f.Name);
            sb.AppendLine($"            if ({acc} is not null) value.{f.Name} = {acc}.ToArray();");
        }
        sb.AppendLine("            return value;");
        sb.AppendLine("        }");
        sb.AppendLine();

        // byte[] helpers — inline ref struct usage (no Func/Action)
        sb.AppendLine($"        public static byte[] Serialize_{safe}({typeName} value)");
        sb.AppendLine("        {");
        sb.AppendLine("            var buffer = new ArrayBufferWriter<byte>(128);");
        sb.AppendLine("            var writer = new ProtoWireWriter(buffer);");
        sb.AppendLine($"            Write_{safe}(ref writer, value);");
        sb.AppendLine("            writer.Dispose();");
        sb.AppendLine("            return buffer.WrittenSpan.ToArray();");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.AppendLine($"        public static {typeName} Deserialize_{safe}(byte[] payload)");
        sb.AppendLine("        {");
        sb.AppendLine("            var reader = new ProtoWireReader(payload);");
        sb.AppendLine($"            return Read_{safe}(ref reader);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.AppendLine($"        public static readonly Marshaller<{typeName}> Marshaller_{safe} = Marshallers.Create(");
        sb.AppendLine($"            (arg, ctx) => ctx.Complete(Serialize_{safe}(arg)),");
        sb.AppendLine($"            ctx => Deserialize_{safe}(ctx.PayloadAsNewBuffer()));");
        sb.AppendLine();
    }

    private static void EmitWriteField(StringBuilder sb, ProtoFieldModel f, Dictionary<string, MessageShape> byClr)
    {
        var access = "value." + f.Name;
        var isNullable = f.IsNullable;
        var proto = f.ProtoType.Trim();
        var kind = f.Kind;

        if (kind == FieldKind.Repeated)
        {
            sb.AppendLine($"            if ({access} is not null)");
            sb.AppendLine("            {");
            sb.AppendLine($"                foreach (var __item in {access})");
            sb.AppendLine("                {");
            EmitWriteOne(sb, f.Number, f.ElementProtoType, f.ElementClrHint, f.ElementKind, "__item", isNullable: false, byClr, "                    ");
            sb.AppendLine("                }");
            sb.AppendLine("            }");
            return;
        }

        EmitWriteOne(sb, f.Number, proto, f.ClrTypeHint, kind, access, isNullable, byClr, "            ");
    }

    private static void EmitWriteOne(
        StringBuilder sb, int number, string proto, string clrHint, FieldKind kind,
        string access, bool isNullable, Dictionary<string, MessageShape> byClr, string indent)
    {
        void L(string s) => sb.Append(indent).AppendLine(s);

        MessageShape? nested = null;
        if (TryFindNested(byClr, clrHint, out nested) ||
            (kind == FieldKind.Message && TryFindNested(byClr, SimpleTypeName(clrHint), out nested)))
        {
            if (nested is null)
                return;
            var nestedSafe = Sanitize(nested.MessageName);
            if (isNullable)
            {
                L($"if ({access} is not null)");
                L("{");
                L($"    var __buf = new ArrayBufferWriter<byte>(64);");
                L($"    var __nw = new ProtoWireWriter(__buf);");
                L($"    Write_{nestedSafe}(ref __nw, {access});");
                L($"    __nw.Dispose();");
                L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                L("}");
            }
            else
            {
                L($"{{");
                L($"    var __buf = new ArrayBufferWriter<byte>(64);");
                L($"    var __nw = new ProtoWireWriter(__buf);");
                L($"    Write_{nestedSafe}(ref __nw, {access});");
                L($"    __nw.Dispose();");
                L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                L("}");
            }
            return;
        }

        switch (kind)
        {
            case FieldKind.Enum:
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    writer.WriteTag({number}, ProtoWireType.Varint);");
                    L($"    writer.WriteInt32((int){access}.Value);");
                    L("}");
                }
                else
                {
                    L($"writer.WriteTag({number}, ProtoWireType.Varint);");
                    L($"writer.WriteInt32((int){access});");
                }
                break;
            case FieldKind.Int32:
                WriteVarintScalar(L, number, access, isNullable, "WriteInt32", cast: null);
                break;
            case FieldKind.Int64:
                WriteVarintScalar(L, number, access, isNullable, "WriteInt64", cast: null);
                break;
            case FieldKind.UInt32:
                WriteVarintScalar(L, number, access, isNullable, "WriteUInt32", cast: null);
                break;
            case FieldKind.UInt64:
                WriteVarintScalar(L, number, access, isNullable, "WriteUInt64", cast: null);
                break;
            case FieldKind.Bool:
                WriteVarintScalar(L, number, access, isNullable, "WriteBool", cast: null);
                break;
            case FieldKind.Float:
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    writer.WriteTag({number}, ProtoWireType.Fixed32);");
                    L($"    writer.WriteFloat({access}.Value);");
                    L("}");
                }
                else
                {
                    L($"writer.WriteTag({number}, ProtoWireType.Fixed32);");
                    L($"writer.WriteFloat({access});");
                }
                break;
            case FieldKind.Double:
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    writer.WriteTag({number}, ProtoWireType.Fixed64);");
                    L($"    writer.WriteDouble({access}.Value);");
                    L("}");
                }
                else
                {
                    L($"writer.WriteTag({number}, ProtoWireType.Fixed64);");
                    L($"writer.WriteDouble({access});");
                }
                break;
            case FieldKind.String:
            {
                // char / char? encode as 1-char string; string as usual
                if (IsCharClr(clrHint))
                {
                    if (isNullable)
                    {
                        L($"if ({access}.HasValue)");
                        L("{");
                        L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    writer.WriteString({access}.Value.ToString());");
                        L("}");
                    }
                    else
                    {
                        L($"writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"writer.WriteString({access}.ToString());");
                    }
                }
                else if (isNullable)
                {
                    L($"if ({access} is not null)");
                    L("{");
                    L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    writer.WriteString({access});");
                    L("}");
                }
                else
                {
                    L($"writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"writer.WriteString({access} ?? string.Empty);");
                }
                break;
            }
            case FieldKind.Bytes:
                L($"if ({access} is not null)");
                L("{");
                L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                L($"    writer.WriteBytes({access});");
                L("}");
                break;
            case FieldKind.Guid:
                // bytes (16) — Guid is not a protobuf scalar
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    writer.WriteBytes({access}.Value.ToByteArray());");
                    L("}");
                }
                else
                {
                    L($"writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"writer.WriteBytes({access}.ToByteArray());");
                }
                break;
            case FieldKind.DateTime:
                // google.protobuf.Timestamp — DateTime and DateTimeOffset are different CLR types
                if (IsDateTimeOffsetClr(clrHint))
                {
                    if (isNullable)
                    {
                        L($"if ({access}.HasValue)");
                        L("{");
                        L($"    var __dto = {access}.Value;");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                    else
                    {
                        L($"{{");
                        L($"    var __dto = {access};");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                }
                else
                {
                    // System.DateTime
                    if (isNullable)
                    {
                        L($"if ({access}.HasValue)");
                        L("{");
                        L($"    var __dt = {access}.Value.Kind == DateTimeKind.Unspecified ? DateTime.SpecifyKind({access}.Value, DateTimeKind.Utc) : {access}.Value.ToUniversalTime();");
                        L($"    var __dto = new DateTimeOffset(__dt);");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                    else
                    {
                        L($"{{");
                        L($"    var __dt = {access}.Kind == DateTimeKind.Unspecified ? DateTime.SpecifyKind({access}, DateTimeKind.Utc) : {access}.ToUniversalTime();");
                        L($"    var __dto = new DateTimeOffset(__dt);");
                        L($"    var __sec = __dto.ToUnixTimeSeconds();");
                        L($"    var __nano = (int)((__dto.UtcTicks % TimeSpan.TicksPerSecond) * 100);");
                        L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                        L($"    var __nw = new ProtoWireWriter(__buf);");
                        L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                        L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                        L($"    __nw.Dispose();");
                        L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                        L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                        L("}");
                    }
                }
                break;
            case FieldKind.TimeSpan:
                // google.protobuf.Duration { int64 seconds=1; int32 nanos=2; }
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    var __ts = {access}.Value;");
                    L($"    var __sec = (long)__ts.TotalSeconds;");
                    L($"    var __nano = (int)((__ts.Ticks % TimeSpan.TicksPerSecond) * 100);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                    L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                    L($"    __nw.Dispose();");
                    L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                else
                {
                    L($"{{");
                    L($"    var __ts = {access};");
                    L($"    var __sec = (long)__ts.TotalSeconds;");
                    L($"    var __nano = (int)((__ts.Ticks % TimeSpan.TicksPerSecond) * 100);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__sec);");
                    L($"    if (__nano != 0) {{ __nw.WriteTag(2, ProtoWireType.Varint); __nw.WriteInt32(__nano); }}");
                    L($"    __nw.Dispose();");
                    L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                break;
            case FieldKind.Decimal:
                // DecimalValue { int64 units=1; sfixed32 nanos=2; } — MS docs
                if (isNullable)
                {
                    L($"if ({access}.HasValue)");
                    L("{");
                    L($"    var __dec = {access}.Value;");
                    L($"    var __units = decimal.ToInt64(__dec);");
                    L($"    var __nanos = decimal.ToInt32((__dec - __units) * 1_000_000_000m);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__units);");
                    L($"    if (__nanos != 0) {{ __nw.WriteTag(2, ProtoWireType.Fixed32); __nw.WriteFixed32(unchecked((uint)__nanos)); }}");
                    L($"    __nw.Dispose();");
                    L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                else
                {
                    L($"{{");
                    L($"    var __dec = {access};");
                    L($"    var __units = decimal.ToInt64(__dec);");
                    L($"    var __nanos = decimal.ToInt32((__dec - __units) * 1_000_000_000m);");
                    L($"    var __buf = new ArrayBufferWriter<byte>(16);");
                    L($"    var __nw = new ProtoWireWriter(__buf);");
                    L($"    __nw.WriteTag(1, ProtoWireType.Varint); __nw.WriteInt64(__units);");
                    L($"    if (__nanos != 0) {{ __nw.WriteTag(2, ProtoWireType.Fixed32); __nw.WriteFixed32(unchecked((uint)__nanos)); }}");
                    L($"    __nw.Dispose();");
                    L($"    writer.WriteTag({number}, ProtoWireType.LengthDelimited);");
                    L($"    writer.WriteLengthDelimitedBytes(__buf.WrittenSpan);");
                    L("}");
                }
                break;
            default:
                L($"// unhandled field kind {kind} ({proto})");
                break;
        }
    }

    private static void WriteVarintScalar(Action<string> L, int number, string access, bool isNullable, string method, string? cast)
    {
        // Explicit cast so byte/sbyte/short/ushort/nint/nuint compile against WriteInt32/WriteUInt32/WriteInt64/WriteUInt64
        var arg = method switch
        {
            "WriteInt32" => $"(int)({access})",
            "WriteUInt32" => $"(uint)({access})",
            "WriteInt64" => $"(long)({access})",
            "WriteUInt64" => $"(ulong)({access})",
            "WriteBool" => access,
            _ => access
        };
        var argN = method switch
        {
            "WriteInt32" => $"(int)({access}.Value)",
            "WriteUInt32" => $"(uint)({access}.Value)",
            "WriteInt64" => $"(long)({access}.Value)",
            "WriteUInt64" => $"(ulong)({access}.Value)",
            "WriteBool" => $"{access}.Value",
            _ => $"{access}.Value"
        };

        if (isNullable)
        {
            L($"if ({access}.HasValue)");
            L("{");
            L($"    writer.WriteTag({number}, ProtoWireType.Varint);");
            L($"    writer.{method}({argN});");
            L("}");
        }
        else
        {
            L($"writer.WriteTag({number}, ProtoWireType.Varint);");
            L($"writer.{method}({arg});");
        }
    }

    private static void EmitReadCase(StringBuilder sb, ProtoFieldModel f, Dictionary<string, MessageShape> byClr)
    {
        var access = "value." + f.Name;
        sb.AppendLine($"                    case {f.Number}:");

        if (f.Kind == FieldKind.Repeated)
        {
            if (f.IsArray)
            {
                var acc = AccName(f.Name);
                sb.AppendLine($"                        {acc} ??= new global::System.Collections.Generic.List<{f.ElementClrHint}>();");
                EmitReadOneInto(sb, f.ElementKind, f.ElementClrHint, f.ElementProtoType, access, byClr, listAdd: acc);
            }
            else
            {
                // List / IList / ICollection — use concrete List for accumulation when null
                sb.AppendLine($"                        {access} ??= new global::System.Collections.Generic.List<{f.ElementClrHint}>();");
                EmitReadOneInto(sb, f.ElementKind, f.ElementClrHint, f.ElementProtoType, access, byClr, listAdd: access);
            }
            return;
        }

        MessageShape? nested = null;
        if (TryFindNested(byClr, f.ClrTypeHint, out nested) ||
            (f.Kind == FieldKind.Message && TryFindNested(byClr, SimpleTypeName(f.ClrTypeHint), out nested)))
        {
            if (nested is null)
            {
                sb.AppendLine("                        reader.SkipField(wireType); break;");
                return;
            }
            sb.AppendLine("                    {");
            sb.AppendLine("                        var __sub = reader.ReadBytes();");
            sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
            sb.AppendLine($"                        {access} = Read_{Sanitize(nested.MessageName)}(ref __nr);");
            sb.AppendLine("                    }");
            sb.AppendLine("                        break;");
            return;
        }

        EmitReadOneInto(sb, f.Kind, f.ClrTypeHint, f.ProtoType, access, byClr, listAdd: null);
    }

    private static void EmitReadOneInto(
        StringBuilder sb, FieldKind kind, string clrHint, string proto, string access,
        Dictionary<string, MessageShape> byClr, string? listAdd)
    {
        void AssignLine(string expr)
        {
            var castExpr = CastToClr(clrHint, expr);
            if (listAdd is not null)
                sb.AppendLine($"                        {listAdd}.Add({castExpr}); break;");
            else
                sb.AppendLine($"                        {access} = {castExpr}; break;");
        }

        switch (kind)
        {
            case FieldKind.Message:
            {
                MessageShape? nestedMsg = null;
                if (!TryFindNested(byClr, clrHint, out nestedMsg))
                    TryFindNested(byClr, SimpleTypeName(clrHint), out nestedMsg);
                if (nestedMsg is null)
                {
                    sb.AppendLine("                        reader.SkipField(wireType); break;");
                    break;
                }
                var nestedSafe = Sanitize(nestedMsg.MessageName);
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine($"                        var __nm = Read_{nestedSafe}(ref __nr);");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__nm);");
                else
                    sb.AppendLine($"                        {access} = __nm;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            }
            case FieldKind.Enum:
                // Enum underlying is int on the wire
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(({clrHint})reader.ReadInt32()); break;");
                else
                    sb.AppendLine($"                        {access} = ({clrHint})reader.ReadInt32(); break;");
                break;
            case FieldKind.Int32:
                AssignLine("reader.ReadInt32()");
                break;
            case FieldKind.Int64:
                AssignLine("reader.ReadInt64()");
                break;
            case FieldKind.UInt32:
                AssignLine("reader.ReadUInt32()");
                break;
            case FieldKind.UInt64:
                AssignLine("reader.ReadUInt64()");
                break;
            case FieldKind.Bool:
                AssignLine("reader.ReadBool()");
                break;
            case FieldKind.Float:
                AssignLine("reader.ReadFloat()");
                break;
            case FieldKind.Double:
                AssignLine("reader.ReadDouble()");
                break;
            case FieldKind.String:
                if (IsCharClr(clrHint))
                {
                    sb.AppendLine("                    {");
                    sb.AppendLine("                        var __cs = reader.ReadString();");
                    sb.AppendLine("                        var __ch = string.IsNullOrEmpty(__cs) ? default(char) : __cs[0];");
                    if (listAdd is not null)
                        sb.AppendLine($"                        {listAdd}.Add(__ch);");
                    else
                        sb.AppendLine($"                        {access} = __ch;");
                    sb.AppendLine("                    }");
                    sb.AppendLine("                        break;");
                }
                else
                {
                    AssignLine("reader.ReadString()");
                }
                break;
            case FieldKind.Bytes:
                AssignLine("reader.ReadBytes().ToArray()");
                break;
            case FieldKind.Guid:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __gb = reader.ReadBytes();");
                sb.AppendLine("                        var __gv = __gb.Length == 16 ? new Guid(__gb) : default;");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__gv);");
                else
                    sb.AppendLine($"                        {access} = __gv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            case FieldKind.DateTime:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine("                        long __sec = 0; int __nano = 0;");
                sb.AppendLine("                        while (__nr.TryReadTag(out var __f, out var __w))");
                sb.AppendLine("                        {");
                sb.AppendLine("                            if (__f == 1) __sec = __nr.ReadInt64();");
                sb.AppendLine("                            else if (__f == 2) __nano = __nr.ReadInt32();");
                sb.AppendLine("                            else __nr.SkipField(__w);");
                sb.AppendLine("                        }");
                if (IsDateTimeOffsetClr(clrHint))
                {
                    sb.AppendLine("                        var __dtv = DateTimeOffset.FromUnixTimeSeconds(__sec).AddTicks(__nano / 100);");
                }
                else
                {
                    sb.AppendLine("                        var __dtv = DateTimeOffset.FromUnixTimeSeconds(__sec).UtcDateTime.AddTicks(__nano / 100);");
                }
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__dtv);");
                else
                    sb.AppendLine($"                        {access} = __dtv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            case FieldKind.TimeSpan:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine("                        long __sec = 0; int __nano = 0;");
                sb.AppendLine("                        while (__nr.TryReadTag(out var __f, out var __w))");
                sb.AppendLine("                        {");
                sb.AppendLine("                            if (__f == 1) __sec = __nr.ReadInt64();");
                sb.AppendLine("                            else if (__f == 2) __nano = __nr.ReadInt32();");
                sb.AppendLine("                            else __nr.SkipField(__w);");
                sb.AppendLine("                        }");
                sb.AppendLine("                        var __tsv = TimeSpan.FromSeconds(__sec) + TimeSpan.FromTicks(__nano / 100);");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__tsv);");
                else
                    sb.AppendLine($"                        {access} = __tsv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            case FieldKind.Decimal:
                sb.AppendLine("                    {");
                sb.AppendLine("                        var __sub = reader.ReadBytes();");
                sb.AppendLine("                        var __nr = new ProtoWireReader(__sub);");
                sb.AppendLine("                        long __units = 0; int __nanos = 0;");
                sb.AppendLine("                        while (__nr.TryReadTag(out var __f, out var __w))");
                sb.AppendLine("                        {");
                sb.AppendLine("                            if (__f == 1) __units = __nr.ReadInt64();");
                sb.AppendLine("                            else if (__f == 2) __nanos = unchecked((int)__nr.ReadFixed32());");
                sb.AppendLine("                            else __nr.SkipField(__w);");
                sb.AppendLine("                        }");
                sb.AppendLine("                        var __decv = __units + __nanos / 1_000_000_000m;");
                if (listAdd is not null)
                    sb.AppendLine($"                        {listAdd}.Add(__decv);");
                else
                    sb.AppendLine($"                        {access} = __decv;");
                sb.AppendLine("                    }");
                sb.AppendLine("                        break;");
                break;
            default:
                sb.AppendLine("                        reader.SkipField(wireType); break;");
                break;
        }
    }

    private static string AccName(string propName)
        => "__acc_" + propName;

    private static bool IsDateTimeOffsetClr(string clrHint)
    {
        if (string.IsNullOrEmpty(clrHint)) return false;
        var s = clrHint.Trim();
        if (s.EndsWith("?", StringComparison.Ordinal))
            s = s.Substring(0, s.Length - 1);
        return s == "DateTimeOffset"
               || s == "System.DateTimeOffset"
               || s.EndsWith(".DateTimeOffset", StringComparison.Ordinal);
    }

    private static bool IsCharClr(string clrHint)
    {
        if (string.IsNullOrEmpty(clrHint)) return false;
        var s = clrHint.Trim();
        return s == "char" || s == "Char" || s == "System.Char"
            || s == "char?" || s == "System.Char?" || s.EndsWith(".Char", StringComparison.Ordinal);
    }

    /// <summary>
    /// Narrow/widen wire values to the property CLR type (byte, sbyte, short, ushort, nint, nuint, …).
    /// </summary>
    private static string CastToClr(string clrHint, string expr)
    {
        if (string.IsNullOrEmpty(clrHint))
            return expr;

        var s = clrHint.Trim();
        // strip nullable annotation from type name for cast target
        if (s.EndsWith("?", StringComparison.Ordinal))
            s = s.Substring(0, s.Length - 1);

        // global:: prefix types
        var core = s;
        if (core.StartsWith("global::", StringComparison.Ordinal))
            core = core.Substring("global::".Length);

        switch (core)
        {
            case "byte":
            case "Byte":
            case "System.Byte":
                return $"(byte)({expr})";
            case "sbyte":
            case "SByte":
            case "System.SByte":
                return $"(sbyte)({expr})";
            case "short":
            case "Int16":
            case "System.Int16":
                return $"(short)({expr})";
            case "ushort":
            case "UInt16":
            case "System.UInt16":
                return $"(ushort)({expr})";
            case "int":
            case "Int32":
            case "System.Int32":
                return $"(int)({expr})";
            case "uint":
            case "UInt32":
            case "System.UInt32":
                return $"(uint)({expr})";
            case "long":
            case "Int64":
            case "System.Int64":
                return $"(long)({expr})";
            case "ulong":
            case "UInt64":
            case "System.UInt64":
                return $"(ulong)({expr})";
            case "nint":
            case "IntPtr":
            case "System.IntPtr":
                return $"(nint)({expr})";
            case "nuint":
            case "UIntPtr":
            case "System.UIntPtr":
                return $"(nuint)({expr})";
            case "float":
            case "Single":
            case "System.Single":
                return $"(float)({expr})";
            case "double":
            case "Double":
            case "System.Double":
                return $"(double)({expr})";
            default:
                // string, byte[], Guid, custom — no cast (or identity)
                return expr;
        }
    }

    private static bool TryFindNested(Dictionary<string, MessageShape> byClr, string hint, out MessageShape? nested)
    {
        nested = null;
        if (string.IsNullOrEmpty(hint) || byClr.Count == 0)
            return false;

        var normalized = NormalizeClrTypeName(hint);
        if (byClr.TryGetValue(normalized, out nested))
            return true;
        if (byClr.TryGetValue(hint, out nested))
            return true;

        foreach (var m in byClr.Values)
        {
            if (MatchNested(m, hint) || MatchNested(m, normalized))
            {
                nested = m;
                return true;
            }
        }

        var simple = SimpleTypeName(normalized);
        if (!string.IsNullOrEmpty(simple) && simple != normalized)
        {
            foreach (var m in byClr.Values)
            {
                if (string.Equals(m.MessageName, simple, StringComparison.Ordinal) ||
                    string.Equals(Sanitize(m.MessageName), Sanitize(simple), StringComparison.Ordinal))
                {
                    nested = m;
                    return true;
                }
            }
        }

        nested = null;
        return false;
    }

    private static bool MatchNested(MessageShape m, string hint)
    {
        if (string.IsNullOrEmpty(hint)) return false;
        var h = NormalizeClrTypeName(hint);
        return string.Equals(m.MessageName, hint, StringComparison.Ordinal)
               || string.Equals(m.MessageName, h, StringComparison.Ordinal)
               || string.Equals(m.ClrTypeName, h, StringComparison.Ordinal)
               || m.ClrTypeName.EndsWith("." + h, StringComparison.Ordinal)
               || m.ClrTypeName.EndsWith("+" + h, StringComparison.Ordinal)
               || m.ClrTypeName.EndsWith("." + SimpleTypeName(h), StringComparison.Ordinal);
    }

    private static List<MessageShape> CollectMessages(ImmutableArray<GrpcEndpointModel> endpoints)
    {
        // Key by normalized CLR type so NestedItem from multiple parents is registered once.
        var byClr = new Dictionary<string, MessageShape>(StringComparer.Ordinal);
        foreach (var ep in endpoints)
        {
            Add(byClr, ep.RequestTypeName, ep.RequestMessageName, ep.RequestFields, isRef: true);
            Add(byClr, UnwrapTask(ep.ResponseTypeName), ep.ResponseMessageName, ep.ResponseFields, isRef: true);
            if (!ep.NestedMessages.IsDefaultOrEmpty)
            {
                foreach (var n in ep.NestedMessages)
                    Add(byClr, n.ClrTypeName, n.MessageName, n.Fields, n.IsReferenceType);
            }
        }

        // Second pass: collapse by sanitized message name (Write_NestedItem / Marshaller_NestedItem).
        // Different CLR string forms of the same type must not emit duplicate members.
        var bySafeName = new Dictionary<string, MessageShape>(StringComparer.Ordinal);
        foreach (var shape in byClr.Values.Where(m => !string.IsNullOrEmpty(m.ClrTypeName) && m.Fields.Count > 0))
        {
            var safe = Sanitize(shape.MessageName);
            if (!bySafeName.TryGetValue(safe, out var existing))
            {
                bySafeName[safe] = shape;
                continue;
            }
            // Merge any missing fields from the duplicate registration
            foreach (var f in shape.Fields)
            {
                if (existing.Fields.All(x => x.Number != f.Number && x.Name != f.Name))
                    existing.Fields.Add(f);
            }
            // Prefer longer / more qualified CLR name for nested lookup
            if (shape.ClrTypeName.Length > existing.ClrTypeName.Length)
                existing.ClrTypeName = shape.ClrTypeName;
        }

        return bySafeName.Values.ToList();
    }

    private static void Add(
        Dictionary<string, MessageShape> map, string clrType, string messageName,
        ImmutableArray<ProtoFieldModel> fields, bool isRef)
    {
        clrType = NormalizeClrTypeName(UnwrapTask(clrType));
        if (string.IsNullOrEmpty(clrType) || fields.IsDefaultOrEmpty) return;
        if (!map.TryGetValue(clrType, out var shape))
        {
            shape = new MessageShape(clrType, string.IsNullOrEmpty(messageName) ? SimpleTypeName(clrType) : messageName, new List<ProtoFieldModel>(), isRef);
            map[clrType] = shape;
        }
        foreach (var f in fields)
            if (shape.Fields.All(x => x.Number != f.Number))
                shape.Fields.Add(f);
    }

    /// <summary>Strip global:: and normalize whitespace so the same type is one dictionary key.</summary>
    private static string NormalizeClrTypeName(string typeName)
    {
        if (string.IsNullOrEmpty(typeName)) return typeName;
        typeName = typeName.Trim();
        const string globalPrefix = "global::";
        if (typeName.StartsWith(globalPrefix, StringComparison.Ordinal))
            typeName = typeName.Substring(globalPrefix.Length);
        // Nullable annotation may appear as trailing '?' (e.g. NestedItem?)
        if (typeName.EndsWith("?", StringComparison.Ordinal))
            typeName = typeName.Substring(0, typeName.Length - 1);
        return typeName;
    }

    private static string SimpleTypeName(string clrType)
    {
        if (string.IsNullOrEmpty(clrType)) return "Message";
        var s = clrType;
        var gen = s.IndexOf('<');
        if (gen >= 0) s = s.Substring(0, gen);
        var plus = s.LastIndexOf('+');
        if (plus >= 0) return s.Substring(plus + 1);
        var dot = s.LastIndexOf('.');
        return dot >= 0 ? s.Substring(dot + 1) : s;
    }

    private static string UnwrapTask(string typeName)
    {
        if (string.IsNullOrEmpty(typeName)) return typeName;
        foreach (var prefix in new[]
                 {
                     "global::System.Threading.Tasks.Task<", "System.Threading.Tasks.Task<",
                     "global::System.Threading.Tasks.ValueTask<", "System.Threading.Tasks.ValueTask<"
                 })
        {
            var idx = typeName.IndexOf(prefix, StringComparison.Ordinal);
            if (idx >= 0)
            {
                var start = idx + prefix.Length;
                var end = typeName.LastIndexOf('>');
                if (end > start) return typeName.Substring(start, end - start).Trim();
            }
        }
        return typeName;
    }

    private static string Sanitize(string name)
    {
        if (string.IsNullOrEmpty(name)) return "Message";
        var chars = name.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray();
        return new string(chars);
    }

    private sealed class MessageShape
    {
        public string ClrTypeName { get; set; }
        public string MessageName { get; }
        public List<ProtoFieldModel> Fields { get; }
        public bool IsReferenceType { get; }
        public MessageShape(string clr, string msg, List<ProtoFieldModel> fields, bool isRef)
        {
            ClrTypeName = clr;
            MessageName = string.IsNullOrEmpty(msg) ? "Message" : msg;
            Fields = fields;
            IsReferenceType = isRef;
        }
    }
